"""`reports/online.md`: the online evaluation over every saved window: what the policy sampled and
why, what the judge read, the failure clusters, the drift against the offline baseline and the window
before, and the records harvested into the dataset."""

from collections import Counter
from pathlib import Path

import yaml

from ..ingest.report import cell
from .online import RULE_ORDER, Cluster, Rate, Window
from .runs import Run


def write_report(
    windows: list[Window],
    rates: list[dict[str, float | None]],
    drifts: list[list[Rate]],
    groups: list[list[Cluster]],
    baseline: Run,
    live_total: int,
    harvested_path: Path,
    output: Path,
) -> None:
    lines: list[str] = []
    w = lines.append
    w("# Online evaluation: live traffic, sampled and read")
    w("")
    w(
        f"Generated by `uv run infra-docs-rag online report` from {len(windows)} saved window(s) under `eval/online/` "
        f"and the trace log ({live_total} live traces in all: what the service and `answer` wrote, runs and the canary "
        f"left out). The sampling policy is [`eval/online.yaml`](../eval/online.yaml); the offline baseline the drift "
        f"is read against is the pinned dataset run `{baseline.name}`. What each rule and rate means is in "
        "[`eval/SPEC.md`](../eval/SPEC.md), section 12."
    )
    w("")
    w(
        "**Where the traffic comes from.** The service has no public users yet; the live traces are the questions in "
        "`scripts/traffic.py`, forty written by hand with the mix a benchmark rarely has (long ones, identifiers, typos, "
        "Portuguese, off-topic, an injection, follow-ups), posted to the running service with feedback on some of them the "
        "way a person would give it. Not sampled from anyone's logs; the pipeline, the sampler, the judge and the harvest "
        "run on them exactly as they would on real traffic."
    )
    w("")
    w("## Summary")
    w("")
    w("| Window | Live | Sampled | Judged | Grounded (judge) | Failed | Drift flagged | Clusters |")
    w("|---|---:|---:|---:|---:|---:|---|---:|")
    for win, d, g in zip(windows, drifts, groups, strict=True):
        judged = [s for s in win.samples if s.judgement is not None]
        grounded = [s for s in judged if s.judgement.grounded >= 0.5]
        failed = [s for s in win.samples if s.failed]
        flagged = [r.name for r in d if r.drifted]
        w(
            f"| `{win.name}` | {win.live} | {len(win.samples)} | {len(judged)} | "
            f"{len(grounded)}/{len(judged)} | {len(failed)} | {', '.join(f'`{x}`' for x in flagged) or 'none'} | {len(g)} |"
        )
    w("")
    if not windows:
        w("No window sampled yet: `online sample` picks one out of the trace log.")
        w("")

    policy = windows[-1].policy if windows else None
    w("## 1. The sampling policy")
    w("")
    if policy:
        w(
            f"A window is {policy.window_days} days of live traces. Every rule that fires is recorded on the sample; "
            f"`random` keeps a stable {policy.random_share:.0%} of the traces no rule picked, so the window stays representative; "
            f"at most {policy.max_samples} samples a window."
        )
        w("")
        w("| Rule | Fires when | Why |")
        w("|---|---|---|")
        when = {
            "dissatisfied": "a person marked the answer not helpful (`POST /feedback`)",
            "uncited": f"answered with under {policy.uncited_claim_share:.0%} of the claims cited",
            "low-confidence": f"answered with the best passage's cosine under {policy.low_confidence_top_score:.2f}",
            "no-answer": "the abstention sentence (no passage qualified, or the model abstained)",
            "long-context": f"the passages at or over {policy.long_context_share:.0%} of the token budget, or some left out",
            "long-query": f"over {policy.long_query_words} words",
            "identifier": "a camelCase, dotted, snake_case or `--flag` token in the question",
            "error": "the model call failed",
            "random": f"a stable {policy.random_share:.0%} of the rest",
        }
        for rule in RULE_ORDER:
            w(f"| `{rule}` | {when[rule]} | {cell(policy.rules.get(rule, ''))} |")
        w("")

    for win, _rate, d, g in zip(windows, rates, drifts, groups, strict=True):
        w(f"## 2. Window `{win.name}` ({win.since[:10]} → {win.until[:10]})")
        w("")
        by_rule = Counter(r for s in win.samples for r in s.rules)
        w(
            f"{win.live} live traces, {len(win.samples)} sampled: "
            + ", ".join(f"{by_rule[r]} `{r}`" for r in RULE_ORDER if by_rule[r])
            + (f"; judged {win.judged_at[:10]}" if win.judged_at else "; not judged yet")
            + "."
        )
        w("")
        w("**The samples**")
        w("")
        w(
            "| Trace | Rules | Outcome | Top cosine | Claims cited | Feedback | Judge grounded · fabricated | Question |"
        )
        w("|---|---|---|---:|---:|---|---|---|")
        for s in win.samples:
            j = s.judgement
            w(
                f"| `{s.trace_id}` | {', '.join(f'`{r}`' for r in s.rules)} | {s.outcome} | "
                f"{f'{s.top_score:.2f}' if s.top_score is not None else '–'} | "
                f"{f'{s.claim_share:.0%}' if s.answered else '–'} | "
                f"{'not helpful' if s.helpful is False else 'helpful' if s.helpful else '–'}"
                + (f" ({cell(s.note)})" if s.note else "")
                + f" | {f'{j.grounded:.2f} · {j.fabricated:.2f}' if j else '–'} | {cell(s.question)} |"
            )
        w("")
        w(
            "**Failure clusters** (the failed samples and the no-answer ones, grouped by the rule that picked them, what happened, and where the first passage came from):"
        )
        w("")
        if not g:
            w("No failed sample in this window.")
        else:
            w("| Cluster | Samples | Traces |")
            w("|---|---:|---|")
            for c in g:
                w(
                    f"| {c.key} | {len(c.samples)} | {', '.join(f'`{x}`' for x in c.samples[:6])}{'…' if len(c.samples) > 6 else ''} |"
                )
        w("")
        w("**Drift** against the offline baseline (the pinned dataset run) and the window before:")
        w("")
        w("| Rate | Baseline | Previous window | This window | Change vs baseline | Threshold | |")
        w("|---|---:|---:|---:|---:|---:|---|")
        for r in d:
            delta = r.delta
            shown_delta = (
                "–"
                if delta is None
                else (
                    f"{delta:+.0%}"
                    if r.shown == "pct"
                    else f"{delta:+.2f}"
                    if r.shown == "num"
                    else f"{delta:+.0f}"
                )
            )
            thr = (
                f"{r.threshold:.0%}"
                if r.shown == "pct"
                else f"{r.threshold:.2f}"
                if r.shown == "num"
                else f"{r.threshold:.0f}"
            )
            w(
                f"| `{r.name}` | {r.fmt(r.baseline)} | {r.fmt(r.previous)} | {r.fmt(r.window)} | {shown_delta} | ± {thr} | {'**drift**' if r.drifted else 'steady'} |"
            )
        w("")
        w(
            "The window's rates are over every live trace in it; the judge's grounded share is over the samples it read. "
            "A benchmark's questions are written to be answerable and the live mix is not, so the no-answer rate drifting up "
            "is the first thing to read: a corpus gap, a floor set too high, or a mix the dataset does not have."
        )
        w("")

    w("## 3. Promoted into the dataset")
    w("")
    if harvested_path.exists():
        data = yaml.safe_load(harvested_path.read_text()) or {}
        rows = data.get("records", [])
        w(
            f"{len(rows)} records harvested from window `{data.get('window', '–')}` into [`{harvested_path.name}`](../{harvested_path}) "
            f"on {str(data.get('harvested_at', ''))[:10]}, each with a reference answer the model drafted from the passages the "
            "service retrieved; `online promote --merge` appends them to `records.yaml`, which moves the dataset version."
        )
        w("")
        w("| Record | Category | Expect | Failure mode | Difficulty | Contexts | Question |")
        w("|---|---|---|---|---|---:|---|")
        for r in rows:
            w(
                f"| `{r['id']}` | {r['category']} | {r['expect']} | `{r['failure_mode']}` | {r['difficulty']} | "
                f"{len(r.get('contexts', []))} | {cell(r['query'])} |"
            )
    else:
        w("Nothing promoted yet: `online promote` drafts records from a window's failed samples.")
    w("")
    w("## 4. Reading the report")
    w("")
    w(
        "The offline gates say whether a change broke what the dataset measures; this report says what the traffic asks "
        "that the dataset does not. A cluster that recurs across windows is a record to add (`online promote`), a floor to "
        "move, or a source to ingest. A `dissatisfied` sample outranks everything else: it is the one signal that comes from "
        "the person the answer was for. Adding harvested records moves the dataset version, so the baseline is run again "
        "and the freeze renewed; that is the loop closing, not a side effect."
    )
    w("")
    w("```sh")
    w(
        "uv run infra-docs-rag serve                                   # the service; POST /answer, POST /feedback"
    )
    w(
        "uv run infra-docs-rag online sample [--until YYYY-MM-DD]      # the window's samples → eval/online/<window>.json"
    )
    w("uv run infra-docs-rag online judge                            # jev reads the answered samples")
    w("uv run infra-docs-rag online report                           # this report")
    w(
        "uv run infra-docs-rag online promote --n 10                   # draft records from the failed samples → eval/dataset/harvested.yaml"
    )
    w(
        "uv run infra-docs-rag online promote --merge                  # append them to records.yaml, then rerun the baseline and freeze"
    )
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")
