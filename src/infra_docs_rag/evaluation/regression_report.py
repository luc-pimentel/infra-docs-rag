"""`reports/regression.md`: a candidate dataset run against the baseline. The decision first, then the
two runs' identities and what differs, the slice gates with the regressions the aggregate would hide
called out, every slice before and after, every record won and lost with the answers behind the
losses, and the matrix before and after."""

from pathlib import Path

from ..ingest.report import cell
from .gates import delta, yn
from .metrics import Metric
from .regression import HEADLINE, Regression, same_passages, slice_sizes
from .report import arrow, passages
from .slices import ALL, SLICE_FIELDS, slice_name

# What the per-slice table shows before and after, in order: name, header.
COLUMNS = [
    ("answers.held", "held"),
    ("retrieval.context_recall", "ctx recall"),
    ("faithfulness.judge_grounded", "grounded"),
    ("faithfulness.judge_fabricated", "fabricated"),
    ("relevance.judge_relevant", "relevant"),
    ("abstention.expected", "abstained ✓"),
    ("abstention.false", "abstained ✗"),
]


def shown(table: dict[str, Metric], name: str) -> str:
    m = table.get(name)
    return "–" if m is None or m.value is None else m.shown


def before_after(before: dict[str, Metric], after: dict[str, Metric], name: str) -> str:
    """`65/74 (88%)` when nothing moved; `65/74 (88%) → 67/74 (91%) ▲` when it did."""
    b, a = before.get(name), after.get(name)
    if a is None or a.value is None:
        return "–"
    if b is None or b.value is None or b.value == a.value:
        return a.shown
    return f"{b.shown} → {a.shown} {arrow(b, a)}"


def result_of(g) -> str:
    if g.skipped:
        return "skipped"
    if g.result.passed:
        return "pass"
    return "**FAIL**" if g.gate.critical else "warn"


def write_report(reg: Regression, output: Path, default_baseline: bool = True) -> None:
    b, c = reg.baseline.manifest, reg.candidate.manifest
    sizes = slice_sizes(reg.records)
    lines: list[str] = []
    w = lines.append

    w("# Regression report")
    w("")
    w(
        f"Generated by `uv run infra-docs-rag dataset compare --candidate {reg.candidate.name}`"
        + ("" if default_baseline else f" `--baseline {reg.baseline.name}`")
        + f" from two saved dataset runs of the same {len(reg.records)} records through the whole pipeline. "
        "Every number is read off the saved answers; the slice gates in [`eval/matrix.yaml`](../eval/matrix.yaml) "
        "say which changes block, and [`eval/baseline.yaml`](../eval/baseline.yaml) pins the baseline. What each "
        "metric reads is in [`eval/SPEC.md`](../eval/SPEC.md), sections 7 and 9."
    )
    w("")
    w("## Summary")
    w("")
    reasons = reg.verdict.split(": ", 1)[1]
    w(f"**Decision: {reg.decision.upper()}.** {reasons[0].upper() + reasons[1:]}.")
    w("")
    if reg.missing:
        w(
            f"{len(reg.missing)} record(s) one of the runs did not answer are left out: "
            + ", ".join(f"`{x}`" for x in reg.missing[:8])
            + ("…" if len(reg.missing) > 8 else "")
            + "."
        )
        w("")
    w("| | Baseline | Candidate |")
    w("|---|---|---|")
    w(f"| Run | `{reg.baseline.name}` | `{reg.candidate.name}` |")
    w(f"| Dataset | `{b.dataset or '–'}` | `{c.dataset or '–'}` |")
    w(f"| Pipeline version | `{b.version}`: {b.description or '–'} | `{c.version}`: {c.description or '–'} |")
    w(f"| Retrieval | `{b.retrieval.label}` | `{c.retrieval.label}` |")
    w(
        f"| Retrieval version | `{b.lineage.retrieval_version if b.lineage else '–'}` | `{c.lineage.retrieval_version if c.lineage else '–'}` |"
    )
    w(
        f"| Prompt | `{b.lineage.prompt_version if b.lineage else b.prompt_sha256}` | `{c.lineage.prompt_version if c.lineage else c.prompt_sha256}` |"
    )
    w(
        f"| Index | `{b.lineage.index_version if b.lineage else '–'}`: {b.index.model} · {b.index.chunking.label} · {b.index.chunks} chunks | "
        f"`{c.lineage.index_version if c.lineage else '–'}`: {c.index.model} · {c.index.chunking.label} · {c.index.chunks} chunks |"
    )
    w(
        f"| Generator | `{b.generator}` via {b.backend}, effort {b.effort} | `{c.generator}` via {c.backend}, effort {c.effort} |"
    )
    w(f"| Judge and reader | {b.judge or 'none'} | {c.judge or 'none'} |")
    w(
        f"| Run | {b.created_at[:10]} at `{b.git_sha}` on {b.machine} | {c.created_at[:10]} at `{c.git_sha}` on {c.machine} |"
    )
    w("")
    if reg.variables:
        w("The variables that move a score, from the two experiment manifests:")
        w("")
        w("| Variable | Baseline | Candidate | |")
        w("|---|---|---|---|")
        for name, before_v, after_v in reg.variables:
            w(f"| {name} | `{before_v}` | `{after_v}` | {'**differs**' if name in reg.differs else 'same'} |")
        w("")
    if not reg.differs:
        w(
            "Nothing differs between the two runs' manifests: the same pipeline on the same dataset, run twice."
        )
    elif reg.differs == ["retrieval"]:
        w("The two runs differ in retrieval only, so every change below is the retrieval's.")
    elif len(reg.differs) == 1:
        w(f"The two runs differ in {reg.differs[0]} only, so every change below is that variable's.")
    else:
        w(
            "**Confounded.** The two runs differ in "
            + ", ".join(reg.differs)
            + ", so a change below cannot be attributed to one of them; the comparison ran with `--allow-confounded`."
        )
    w("")
    hb, ha = reg.headline()
    w("| | Baseline | Candidate | Change |")
    w("|---|---|---|---|")
    w(f"| Expectations held, whole set | {hb.shown} | {ha.shown} | {delta(hb, ha)} {arrow(hb, ha)} |")
    w(
        f"| Records won / lost / changed otherwise | – | {len(reg.wins)} / {len(reg.losses)} / {len(reg.neutral)} | |"
    )
    w(
        f"| Critical gates failed | – | {len(reg.blocking)}"
        + (f" ({len(reg.masked)} hidden by the aggregate)" if reg.masked else "")
        + f" | {len(reg.warnings)} warning(s) |"
    )
    w(
        f"| Matrix targets met | {sum(1 for x in reg.matrix_before if x.passed)} of {sum(1 for x in reg.matrix_before if x.passed is not None)} | "
        f"{sum(1 for x in reg.matrix_after if x.passed)} of {sum(1 for x in reg.matrix_after if x.passed is not None)} | "
        f"{sum(1 for x in reg.matrix_after if x.passed is False and x.entry.blocker)} blocker(s) missed |"
    )
    w(
        f"| Cost, generation | {shown(reg.before[ALL], 'cost.usd_total')} | {shown(reg.after[ALL], 'cost.usd_total')} | "
        f"{delta(reg.before[ALL]['cost.usd_total'], reg.after[ALL]['cost.usd_total'])} |"
    )
    w(
        f"| Latency, end to end at the median | {shown(reg.before[ALL], 'latency.end_to_end_ms_median')} | {shown(reg.after[ALL], 'latency.end_to_end_ms_median')} | "
        f"{delta(reg.before[ALL]['latency.end_to_end_ms_median'], reg.after[ALL]['latency.end_to_end_ms_median'])} |"
    )
    w("")

    w("## 1. The gates")
    w("")
    w(
        "Each gate reads one metric on one slice: `min` and `max` against a fixed value, `no-drop` and `no-rise` "
        "against the baseline with the tolerance the gate names. A critical gate that fails blocks the change "
        "(the command exits 1) whatever the whole set did; the others warn."
    )
    w("")
    w("| Slice | n | Metric | Rule | Baseline | Candidate | Change | Result | Why |")
    w("|---|---:|---|---|---|---|---|---|---|")
    for g in reg.gates:
        res = g.result
        w(
            f"| `{g.gate.slice}` | {sizes.get(g.gate.slice, 0)} | `{g.gate.metric}` | {g.gate.label} | "
            f"{res.baseline.shown if res.baseline else '–'} | {res.candidate.shown} | "
            f"{delta(res.baseline, res.candidate) if res.baseline and res.candidate.value is not None else '–'} | "
            f"{result_of(g)} | {cell(g.gate.why)} |"
        )
    w("")
    if reg.masked:
        w(
            f"**Hidden by the aggregate.** `{HEADLINE}` over the whole set went from {hb.shown} to {ha.shown}, "
            f"{'up' if reg.aggregate_improved else 'flat'}, and "
            f"{len(reg.masked)} critical gate(s) still fail on a slice: "
            + "; ".join(f"`{g.gate.slice}` `{g.gate.metric}` {g.result.detail}" for g in reg.masked)
            + ". A score over every record would have shipped this change; the slice gates are what catch it."
        )
        w("")
    elif reg.blocking:
        w(
            "The failed gate(s) are on the whole set or the whole set dropped too, so the aggregate would have "
            "shown the regression as well."
        )
        w("")

    w("## 2. Scores by slice, before and after")
    w("")
    w(
        "A cell shows the candidate's value, or `baseline → candidate` with ▲ for a change for the better and ▼ "
        "for the worse, in the metric's own direction. held: the record's expectation held. ctx recall: the share "
        "of the record's named passages the model read. grounded, fabricated: the judge at its calibrated "
        "thresholds. relevant: the reader. abstained ✓: records expecting an abstention that got one; abstained ✗: "
        "records expecting an answer that got one. A slice of five records moves by 20% when one flips."
    )
    w("")
    header = "| Slice | n | " + " | ".join(h for _, h in COLUMNS) + " |"
    rule = "|---|---:|" + "---|" * len(COLUMNS)

    def row(name: str) -> str:
        return (
            f"| `{name}` | {sizes[name]} | "
            + " | ".join(before_after(reg.before[name], reg.after[name], col) for col, _ in COLUMNS)
            + " |"
        )

    w("**Overall**")
    w("")
    w(header)
    w(rule)
    w(row(ALL))
    w("")
    for field in SLICE_FIELDS:
        w(f"**By {field.replace('_', ' ')}**")
        w("")
        w(header)
        w(rule)
        for v in sorted({getattr(r, field) for r in reg.records}):
            name = slice_name(field, v)
            if name in reg.after:
                w(row(name))
        w("")

    w("## 3. Record by record")
    w("")
    by_record = {r.id: r for r in reg.records}
    if not reg.changed:
        w("No record's outcome, verdict or right-passage checks changed between the two runs.")
        w("")
    else:
        same = reg.same_passages
        w(
            f"{len(reg.changed)} records differ: **{len(reg.wins)} won** (hold now and did not), "
            f"**{len(reg.losses)} lost** (held and no longer do), {len(reg.neutral)} changed without the verdict flipping. "
            + (
                f"{len(same)} of them ({', '.join(f'`{x.id}`' for x in same)}) read the same passages in the same "
                "order in both runs, so the flip is the generator's variance, not the change under test; the "
                f"other {len(reg.changed) - len(same)} read a different context."
                if same
                else "Every one of them read a different context, so every flip is the change under test."
            )
        )
        w("")
        w("| Record | Category | Failure mode | Split | What changed | Passages | Before | After | |")
        w("|---|---|---|---|---|---|---|---|:-:|")
        for x in reg.changed:
            r = by_record[x.id]
            mark = "▲ won" if x.better is True else "▼ lost" if x.better is False else "="
            w(
                f"| `{x.id}` | {r.category} | `{r.failure_mode}` | {r.split} | {'; '.join(x.what)} | "
                f"{'same' if same_passages(x) else 'changed'} | {case_shown(x.before)} | {case_shown(x.after)} | {mark} |"
            )
        w("")
        if reg.losses:
            w("The losses in full, with the reference beside each:")
            w("")
            for x in reg.losses:
                r = by_record[x.id]
                w(
                    f"### `{x.id}` · {r.category} · `{r.failure_mode}` · expected {r.expect}: {x.after.verdict}"
                )
                w("")
                w(f"**Q:** {x.after.question}")
                w("")
                w(f"**Reference:** {' '.join(r.reference_answer.split())}")
                w("")
                w(
                    f"**Baseline** ({x.before.verdict}): {' '.join((x.before.marked or x.before.reason or x.before.outcome).split())}"
                )
                w("")
                w(
                    "Passages: "
                    + passages(x.before)
                    + f". Named: {', '.join(f'`{k}`' for k in r.contexts) or '–'}."
                )
                w("")
                w(
                    f"**Candidate** ({x.after.verdict}): {' '.join((x.after.marked or x.after.reason or x.after.outcome).split())}"
                )
                w("")
                w("Passages: " + passages(x.after) + ".")
                w("")
                if x.before.trace_id or x.after.trace_id:
                    w(
                        f"Traces: baseline `{x.before.trace_id or '–'}`, candidate `{x.after.trace_id or '–'}` "
                        f"(`traces.jsonl` beside each run; `dataset diagnose --run {reg.candidate.name}` reads them)."
                    )
                    w("")
        if reg.wins:
            w("The wins, in a line each:")
            w("")
            for x in reg.wins:
                r = by_record[x.id]
                w(
                    f"- `{x.id}` ({r.category}, `{r.failure_mode}`): {x.before.verdict} → {x.after.verdict}. "
                    f"Read before: {passages(x.before)}; after: {passages(x.after)}."
                )
            w("")

    w("## 4. The matrix, before and after")
    w("")
    w(
        "Each failure mode's metric on the records designed for it, against its threshold, in both runs. A "
        "**blocker** missed is a condition the pipeline must not ship with."
    )
    w("")
    w("| Failure mode | Metric | Threshold | Slice | Baseline | Candidate | Before | After |")
    w("|---|---|---|---|---|---|---|---|")
    after_by = {x.entry.failure_mode: x for x in reg.matrix_after}
    for x in reg.matrix_before:
        e = x.entry
        y = after_by[e.failure_mode]
        bound = f"{'≥' if e.rule == 'min' else '≤'} {e.value:g}"
        w(
            f"| `{e.failure_mode}` | `{e.metric}` | {bound}{' · blocker' if e.blocker else ''} | `{e.slice}` | "
            f"{x.metric.shown if x.metric and x.metric.value is not None else '–'} | "
            f"{y.metric.shown if y.metric and y.metric.value is not None else '–'} | {mark_of(x.passed)} | {mark_of(y.passed)} |"
        )
    w("")

    w("## 5. Reading the report")
    w("")
    w(
        "The decision is **block** when a critical gate fails, on any slice, whatever the whole set did; **hold** "
        "when every critical gate passes and the change still lost more records than it won, or the whole set "
        "holds fewer within the tolerance, so a person reads the losses and decides; **ship** otherwise. The "
        "baseline is the pinned run in `eval/baseline.yaml`; `dataset compare` refuses a pin whose run or dataset "
        "no longer match, so a number here is always against the reference the pin names. Costs are at API list "
        "prices for the tokens the run used, whatever it was billed to; latency is on the machine named above."
    )
    w("")
    w("```sh")
    w(
        "uv run infra-docs-rag dataset run --generator claude-code --version <name>   # answer every record under a version from eval/versions.yaml"
    )
    w(
        f"uv run infra-docs-rag dataset compare --candidate {reg.candidate.name}   # this report; exit 1 when the decision is block"
    )
    w(
        "uv run infra-docs-rag dataset baseline check                               # the pin against its run and the dataset"
    )
    w(
        "uv run infra-docs-rag dataset baseline set --run <run> --note '…'          # make a run the new baseline"
    )
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")


def mark_of(passed: bool | None) -> str:
    return "–" if passed is None else ("pass" if passed else "**fail**")


def case_shown(c) -> str:
    return (
        f"{c.outcome}, right read {yn(c.right_retrieved)}, right cited {yn(c.right_cited)}, {c.claim_share:.0%} of claims cited"
        if c.answered
        else f"{c.outcome}, right read {yn(c.right_retrieved)}"
    )
