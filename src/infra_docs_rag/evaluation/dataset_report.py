"""`reports/dataset.md`: what the dataset holds, where each record came from, what the saved runs did
with it, and what the audit of the generated testset decided."""

from collections import Counter, defaultdict
from pathlib import Path

from ..chunk.chunks import Chunk
from ..ingest.report import cell, excerpt
from .dataset import CATEGORIES, FAILURE_MODES, OBSERVABLE, Dataset, Observation, Record


def pct(part: int, whole: int) -> str:
    return f"{part}/{whole} ({part / whole:.0%})" if whole else "–"


def short_run(name: str) -> str:
    return name.replace("-claude-code", "")


def write_report(
    ds: Dataset,
    observed: dict[str, list[Observation]],
    chunks: list[Chunk],
    run_names: list[str],
    output: Path,
) -> None:
    curated, kept, records = ds.curated.records, ds.kept, ds.records
    by_chunk = {c.chunk_id: c for c in chunks}
    lines: list[str] = []
    w = lines.append

    w("# Evaluation dataset")
    w("")
    w(
        "Generated by `uv run infra-docs-rag dataset report` from [`eval/dataset/records.yaml`](../eval/dataset/records.yaml), "
        "[`generated.yaml`](../eval/dataset/generated.yaml) and [`audit.yaml`](../eval/dataset/audit.yaml), "
        f"against the `{ds.curated.chunking}` chunks and the saved runs under `eval/runs/`. "
        "The schema is [`schema.json`](../eval/dataset/schema.json); what each field means is in "
        "[`eval/SPEC.md`](../eval/SPEC.md), section 6."
    )
    w("")
    w("## Summary")
    w("")
    n_gen = len(ds.generated.examples) if ds.generated else 0
    decisions = Counter(d.decision for d in ds.audit.decisions) if ds.audit else Counter()
    w("| | |")
    w("|---|---|")
    w(f"| Curated records | {len(curated)} |")
    w(
        f"| Generated examples | {n_gen} ({decisions['kept']} kept, {decisions['edited']} edited, {decisions['discarded']} discarded) |"
    )
    w(f"| Dataset | {len(records)} records |")
    w(f"| Categories | {', '.join(f'{c} {sum(r.category == c for r in curated)}' for c in CATEGORIES)} |")
    w(
        f"| Splits | dev {sum(r.split == 'dev' for r in records)}, test {sum(r.split == 'test' for r in records)} |"
    )
    w(f"| Origins | {', '.join(f'{o} {n}' for o, n in sorted(Counter(r.origin for r in records).items()))} |")
    w(
        f"| Passages named as contexts | {len({c for r in records for c in r.contexts})} of {len(chunks)} chunks, {len({s for r in records for s in r.source_doc_ids})} sources |"
    )
    w(f"| Saved runs read | {', '.join(f'`{short_run(n)}`' for n in run_names) or 'none'} |")
    w("")
    with_history = [r for r in curated if observed.get(r.id)]
    failed_once = [r for r in with_history if any(o.modes for o in observed[r.id])]
    w(
        f"{len(with_history)} of the {len(curated)} curated records come from benchmark questions the runs have "
        f"answered; {len(failed_once)} of those showed a failure in at least one run, which is why they are here. "
        f"The {len(curated) - len(with_history)} others are written for failure modes the runs cannot show yet "
        f"or were taken from the questions people asked the service."
    )
    w("")
    w(
        f"Status: **{'valid' if ds.ok else 'invalid'}**"
        + ("" if ds.ok else f", {len(ds.problems)} problems (see the end)")
    )
    w("")

    w("## 1. The schema")
    w("")
    w("| Field | What it holds |")
    w("|---|---|")
    w("| `id` | unique across the curated and generated records |")
    w("| `query` | the question as a person would type it |")
    w("| `category` | fact-lookup, multi-hop, ambiguous, no-answer, stale, adversarial |")
    w(
        "| `expect` | what a right reply does: `answer`, `abstain` (the fixed sentence), `partial` (answer what the passages cover, name the rest), `clarify` (name the readings, ask which) |"
    )
    w(
        "| `difficulty` | easy (shares the passage's words), medium (paraphrase, or two passages), hard (a condition, an exception, a deprecation, an ambiguity) |"
    )
    w("| `failure_mode` | the failure this example is in the set to catch; `none` for a clean example |")
    w("| `split` | `dev` (read while the scoring rules were revised; tune on these) or `test` (held out) |")
    w(
        "| `origin` | `benchmark` (a question from eval/*.yaml), `traces` (asked of the running service), `hand-written`, `generated` (a model wrote it, the audit kept it) |"
    )
    w("| `source_doc_ids` | the sources the contexts come from |")
    w(
        "| `contexts` | chunk ids of the passages a right answer rests on, under the chunking named at the top of the file; empty for an abstention |"
    )
    w("| `reference_answer` | what a right answer says, from the contexts alone |")
    w(
        "| `tags`, `benchmark_id`, `note` | free tags; the benchmark question the record came from; why it is in the set |"
    )
    w("")
    w("Failure modes:")
    w("")
    w("| Mode | Meaning | Measured by a run? |")
    w("|---|---|---|")
    for mode, meaning in FAILURE_MODES.items():
        w(f"| `{mode}` | {meaning} | {'yes' if mode in OBSERVABLE else 'not yet'} |")
    w("")

    w("## 2. The curated set")
    w("")
    w(
        "Records by category and failure mode. A record's failure mode is the one it is there to catch; what the runs actually showed is in section 3."
    )
    w("")
    modes = [m for m in FAILURE_MODES if any(r.failure_mode == m for r in curated)]
    w("| Category | " + " | ".join(f"`{m}`" for m in modes) + " | Total |")
    w("|---|" + "---:|" * (len(modes) + 1))
    for category in CATEGORIES:
        rows = [r for r in curated if r.category == category]
        w(
            f"| {category} | "
            + " | ".join(str(sum(r.failure_mode == m for r in rows)) or "" for m in modes)
            + f" | {len(rows)} |"
        )
    w(
        "| **Total** | "
        + " | ".join(str(sum(r.failure_mode == m for r in curated)) for m in modes)
        + f" | **{len(curated)}** |"
    )
    w("")
    w("| Category | easy | medium | hard | dev | test | benchmark | traces | hand-written |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for category in CATEGORIES:
        rows = [r for r in curated if r.category == category]
        w(
            f"| {category} | "
            + " | ".join(str(sum(r.difficulty == d for r in rows)) for d in ("easy", "medium", "hard"))
            + " | "
            + " | ".join(str(sum(r.split == s for r in rows)) for s in ("dev", "test"))
            + " | "
            + " | ".join(
                str(sum(r.origin == o for r in rows)) for o in ("benchmark", "traces", "hand-written")
            )
            + " |"
        )
    w("")
    for category in CATEGORIES:
        rows = [r for r in curated if r.category == category]
        w(f"### {category}")
        w("")
        w("| Record | Query | Expect | Difficulty | Failure mode | Split | Contexts |")
        w("|---|---|---|---|---|---|---|")
        for r in rows:
            where = ", ".join(f"`{c}`" for c in r.contexts) if r.contexts else "–"
            w(
                f"| `{r.id}` | {cell(excerpt(r.query, 110))} | {r.expect} | {r.difficulty} | `{r.failure_mode}` | {r.split} | {where} |"
            )
        w("")

    w("## 3. What the runs showed")
    w("")
    w(
        "Each curated record taken from a benchmark question, against every saved run: `held`, or the failure "
        "modes the run showed on it (by the benchmark's own verdict, the right-passage flags, the typed "
        "citations that did not verify, and the judge's reading at the calibrated thresholds). "
        "**Designed** is the record's `failure_mode`; a ✓ in **seen** means a run showed that very mode."
    )
    w("")
    if run_names:
        w("| Record | Designed | Seen | " + " | ".join(f"`{short_run(n)}`" for n in run_names) + " |")
        w("|---|---|:-:|" + "---|" * len(run_names))
        for r in curated:
            obs = observed.get(r.id, [])
            if not obs:
                continue
            by_run = {o.run: o for o in obs}
            seen = any(r.failure_mode in o.modes for o in obs)
            cells = []
            for name in run_names:
                o = by_run.get(name)
                if o is None:
                    cells.append("–")
                elif o.modes:
                    cells.append(", ".join(o.modes))
                else:
                    cells.append("held")
            w(
                f"| `{r.id}` | `{r.failure_mode}` | {'✓' if seen else ('–' if r.failure_mode == 'none' else '✗')} | "
                + " | ".join(cells)
                + " |"
            )
        w("")
        designed = Counter(r.failure_mode for r in with_history)
        seen_count = Counter(
            r.failure_mode for r in with_history if any(r.failure_mode in o.modes for o in observed[r.id])
        )
        w("| Designed failure mode | Records | Seen in a run |")
        w("|---|---:|---:|")
        for mode in FAILURE_MODES:
            if designed[mode]:
                w(f"| `{mode}` | {designed[mode]} | {seen_count[mode]} |")
        w("")
        unmeasured = sorted(
            {r.failure_mode for r in curated if r.failure_mode not in OBSERVABLE and r.failure_mode != "none"}
        )
        if unmeasured:
            w(
                "Not measured by any run yet: "
                + ", ".join(
                    f"`{m}` ({sum(r.failure_mode == m for r in curated)} records)" for m in unmeasured
                )
                + ". These records are in the set for the metrics the next stage adds: a run can show a stale "
                "answer only once something checks the answer against a deprecation the passage states, a wrong "
                "reading only once ambiguity is graded, a missing hop only once an answer is scored against two "
                "passages at once."
            )
            w("")
    else:
        w("No saved run under `eval/runs/`; nothing to compare against.")
        w("")

    w("## 4. The generated testset and its audit")
    w("")
    if ds.generated is None:
        w("No generated set yet: `uv run infra-docs-rag dataset generate` writes one.")
        w("")
    else:
        g = ds.generated
        w(
            f"{len(g.examples)} examples written by `{g.model}` via {g.backend} (effort {g.effort}, prompt "
            f"`{g.prompt_sha256}`, seed {g.seed}, {g.generated_at[:10]}), one per sampled chunk."
        )
        w("")
        if ds.audit is None:
            w("Not audited yet: `eval/dataset/audit.yaml` decides what enters the dataset.")
            w("")
        else:
            w(
                f"Audited by {ds.audit.auditor}: {decisions['kept']} kept, {decisions['edited']} edited, {decisions['discarded']} discarded."
            )
            w("")
            reasons: dict[str, list[str]] = defaultdict(list)
            for d in ds.audit.decisions:
                reasons[d.decision].append(d.id)
            w("| Example | Chunk | Generated query | Decision | Why |")
            w("|---|---|---|---|---|")
            by_id = {x.id: x for x in g.examples}
            for d in ds.audit.decisions:
                x = by_id[d.id]
                w(
                    f"| `{d.id}` | `{x.chunk_id}` | {cell(excerpt(x.query, 90))} | {d.decision} | {cell(excerpt(d.reason, 160))} |"
                )
            w("")
            edited = [d for d in ds.audit.decisions if d.decision == "edited"]
            if edited:
                w("The edits:")
                w("")
                for d in edited:
                    x = by_id[d.id]
                    w(f"- `{d.id}`: {cell(d.reason)}")
                    if d.query:
                        w(f"  - query: ~~{cell(x.query)}~~ → {cell(d.query)}")
                    if d.reference_answer:
                        w(
                            f"  - answer: ~~{cell(excerpt(x.reference_answer, 200))}~~ → {cell(excerpt(d.reference_answer, 200))}"
                        )
                w("")
            by_source = Counter(x.source_doc_id for x in g.examples)
            kept_by_source = Counter(r.source_doc_ids[0] for r in kept)
            w("| Source | Generated | Kept or edited |")
            w("|---|---:|---:|")
            for s, n in sorted(by_source.items()):
                w(f"| `{s}` | {n} | {kept_by_source[s]} |")
            w("")

    w("## 5. Coverage")
    w("")
    sources_all = Counter(c.source_id for c in chunks if not c.source_id.startswith("fixture-"))
    used = Counter()
    for r in records:
        for c in r.contexts:
            if c in by_chunk:
                used[by_chunk[c].source_id] += 1
    w("| Source | Chunks | Named as a context | Records resting on it |")
    w("|---|---:|---:|---:|")
    for s, n in sorted(sources_all.items()):
        named = len({c for r in records for c in r.contexts if c.split(":")[0] == s})
        resting = sum(s in r.source_doc_ids for r in records)
        w(f"| `{s}` | {n} | {named} | {resting} |")
    w("")
    untouched = [s for s in sources_all if not any(s in r.source_doc_ids for r in records)]
    if untouched:
        w("No record rests on " + ", ".join(f"`{s}`" for s in untouched) + ".")
        w("")

    w("## 6. Running it")
    w("")
    w("```sh")
    w(
        "uv run infra-docs-rag dataset check                       # schema, chunk ids, sources, benchmark labels; exit 1 on a problem"
    )
    w(
        "uv run infra-docs-rag dataset generate --n 30 --seed 13   # sample chunks, write eval/dataset/generated.yaml through claude -p"
    )
    w(
        "uv run infra-docs-rag dataset report                      # check, then write reports/dataset.md and eval/dataset/schema.json"
    )
    w("```")
    w("")
    w(
        "A new curated record is an entry in `records.yaml` with its contexts named by chunk id (`search` prints them) "
        "and its reference answer written from those passages alone. A regenerated testset needs a new audit: the "
        "decisions are per example id, and `check` refuses an audit that misses one."
    )
    w("")
    if ds.problems:
        w("## Problems")
        w("")
        for p in ds.problems:
            w(f"- {cell(p)}")
        w("")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")


def by_category(records: list[Record]) -> dict[str, list[Record]]:
    grouped: dict[str, list[Record]] = {c: [] for c in CATEGORIES}
    for r in records:
        grouped[r.category].append(r)
    return grouped
