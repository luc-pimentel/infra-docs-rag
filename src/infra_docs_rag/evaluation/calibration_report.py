"""`reports/calibration.md`: the judge and the mechanical checks against a person's labels."""

from pathlib import Path

from ..generate.judge import BAND
from ..ingest.report import cell
from .calibrate import Agreement, Calibration, Signal, judge_medians
from .metrics import CITED_FLOOR, FABRICATED_CEILING, GROUNDED_FLOOR


def pct(value: float | None) -> str:
    return "–" if value is None else f"{value:.0%}"


def num(value: float | None) -> str:
    return "–" if value is None else f"{value:.2f}"


def row(a: Agreement) -> str:
    return f"{a.n} | {pct(a.agreement)} | {num(a.kappa)} | {pct(a.precision)} | {pct(a.recall)} | {a.tp} / {a.fp} / {a.fn} / {a.tn}"


def excerpt(text: str, limit: int = 600) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def disagreement_rows(s: Signal) -> list[str]:
    lines = [
        f"| Query | {s.what} | Person | Note |",
        "|---|---|---|---|",
    ]
    for d in s.disagreements:
        lines.append(
            f"| `{d.case.id}` | {d.reading or ('yes' if d.signal else 'no')} → {'yes' if d.signal else 'no'} | "
            f"{'yes' if d.person else 'no'} | {cell(d.label.note) or '–'} |"
        )
    return lines


def write_report(cal: Calibration, output: Path) -> None:
    m = cal.run.manifest
    n = len(cal.cases)
    out: list[str] = []
    add = out.append
    add("# Calibration report\n")
    add(
        f"Generated by `uv run infra-docs-rag calibrate` from the saved run `{cal.run.name}` "
        f"(pipeline `{m.version}`, `{m.retrieval.label}`, `{m.generator}` through `{m.backend}`, judged by "
        f"`{m.judge}`, run {m.created_at[:10]} at `{m.git_sha}`) and the hand labels in "
        f"[`eval/labels.yaml`](../eval/labels.yaml) ({n} answers, labelled by {cal.labels.labeler}"
        + (f", guidelines in {cal.labels.guidelines}" if cal.labels.guidelines else "")
        + "). The question: when the judge or a mechanical check says an answer is grounded, is it? "
        "Where the automatic reading and the person disagree, the answer is shown in full, and the revised "
        "scoring rules at the end are what the disagreements taught.\n"
    )

    add("## Summary\n")
    add("| | |\n|---|---|")
    add(f"| Answers labelled | {n} of the {len([c for c in cal.run.cases if c.answered])} the run answered |")
    for axis, count in cal.counts().items():
        add(f"| Labels: {axis} | {count} |")
    best = {s.name: s for s in cal.signals}
    for name in ("judge grounded", "judge fabricated"):
        s = best[name]
        top = s.best
        add(
            f"| {name} | {pct(s.agreement.agreement)} agreement at {s.threshold:.2f} (κ {num(s.agreement.kappa)}); "
            f"best threshold {top[0]:.2f} at {pct(top[1].agreement)} |"
        )
    for name in ("cited share", "right cited", "verdict held"):
        s = best[name]
        add(f"| {name} | {pct(s.agreement.agreement)} agreement (κ {num(s.agreement.kappa)}) |")
    add("")

    add("## 1. What was labelled\n")
    add(
        "Each labelled answer was read against the passages it was given, not against the documentation at "
        "large: a claim that is true but in no passage counts as not grounded. Five labels per answer, "
        "defined in [`eval/SPEC.md`](../eval/SPEC.md):\n"
    )
    add("- **grounded**: every claim in the answer can be read in one of the passages, paraphrase included.")
    add(
        "- **fabricated**: the answer states a specific fact (a number, default, version, name, step) no passage gives."
    )
    add(
        "- **gap named**: the answer says what the passages do not cover or rejects a false premise; n/a when there was nothing to name."
    )
    add("- **correct**: the answer answers the question as far as the passages allow (yes, partial, no).")
    add(
        "- **citations**: the cited passages are where the answer is (right), elsewhere (wrong), or there are none.\n"
    )
    add(
        "| Query | Kind | Expected | Verdict | Grounded | Fabricated | Gap named | Correct | Citations | Judge grounded | Judge fabricated | Cited share |"
    )
    add("|---|---|---|---|---|---|---|---|---|---:|---:|---:|")
    for c, x in cal.cases:
        j = c.judgement
        add(
            f"| `{c.id}` | {c.kind} | {c.expect} | {c.verdict} | {'yes' if x.grounded else 'no'} | "
            f"{'yes' if x.fabricated else 'no'} | {'n/a' if x.gap_named is None else ('yes' if x.gap_named else 'no')} | "
            f"{x.correct} | {x.citations} | {num(j.grounded) if j else '–'} | {num(j.fabricated) if j else '–'} | "
            f"{c.cited_share:.0%} |"
        )
    add("")

    add("## 2. Each signal against the person\n")
    add(
        "Agreement is the share of answers where the signal and the person say the same; κ is Cohen's kappa, "
        "agreement beyond what the two base rates give by chance (0 is chance, 1 is perfect). Precision and "
        "recall take the person's yes as the truth. The counts are yes/yes, signal-only yes, person-only yes, "
        "no/no.\n"
    )
    add(
        "| Signal | Reads as | Against the label | n | Agreement | κ | Precision | Recall | TP / FP / FN / TN |"
    )
    add("|---|---|---|---:|---:|---:|---:|---:|---|")
    for s in cal.signals:
        add(f"| {s.name} | {s.what} | {s.against} | {row(s.agreement)} |")
    add("")
    medians = judge_medians(cal)
    g, f = medians["grounded"], medians["fabricated"]
    add(
        f"The judge's median grounded reading is {g[0]:.2f} on the answers the person called grounded and "
        f"{g[1]:.2f} on the rest; its median fabricated reading is {f[0]:.2f} on the answers the person "
        f"called fabricated and {f[1]:.2f} on the rest.\n"
    )

    add("## 3. Where to read a probability\n")
    add(
        "Each judge probability read as yes at every threshold from 0.30 to 0.90, against the person. The "
        "threshold in use is marked.\n"
    )
    for s in cal.signals:
        if not s.sweep:
            continue
        add(f"**{s.name}**, against *{s.against}*\n")
        add("| Threshold | Agreement | κ | Precision | Recall | TP / FP / FN / TN |")
        add("|---:|---:|---:|---:|---:|---|")
        for t, a in s.sweep:
            mark = " ◀" if s.threshold is not None and abs(t - s.threshold) < 1e-9 else ""
            add(
                f"| {t:.2f}{mark} | {pct(a.agreement)} | {num(a.kappa)} | {pct(a.precision)} | {pct(a.recall)} | {a.tp} / {a.fp} / {a.fn} / {a.tn} |"
            )
        add("")

    add("## 4. Disagreements\n")
    add(
        "Every answer where a signal and the person differ, with the person's note. The answers themselves "
        "follow in section 5.\n"
    )
    any_disagreement = False
    for s in cal.signals:
        if not s.disagreements:
            add(f"**{s.name}**: agrees with the person on every labelled answer.\n")
            continue
        any_disagreement = True
        add(
            f"**{s.name}** ({len(s.disagreements)} of {s.agreement.n}): signal → read as, against the person\n"
        )
        out += disagreement_rows(s)
        add("")
    shown: dict[str, tuple] = {}
    for s in cal.signals:
        for d in s.disagreements:
            shown.setdefault(d.case.id, (d.case, d.label))
    add("## 5. The answers behind the disagreements\n")
    if not any_disagreement:
        add("None: every signal agreed with the person on every labelled answer.\n")
    for c, x in shown.values():
        j = c.judgement
        add(f"### `{c.id}` · {c.kind} · expected to {c.expect}: {c.verdict}\n")
        add(f"**Q:** {c.question}\n")
        add("**A:** " + c.marked.replace("\n", "\n> ") + "\n")
        add(
            "Passages read: "
            + "; ".join(f"[{s.n}] `{cell(s.citation)}`" + (" ✓" if s.right else "") for s in c.sources)
            + "\n"
        )
        if c.uncited:
            add("Uncited: " + "; ".join(f"“{cell(u)}”" for u in c.uncited) + "\n")
        add(
            f"*Person: grounded {'yes' if x.grounded else 'no'}, fabricated {'yes' if x.fabricated else 'no'}, "
            f"correct {x.correct}, citations {x.citations}"
            + (f", gap named {'yes' if x.gap_named else 'no'}" if x.gap_named is not None else "")
            + f". Automatic: cited share {c.cited_share:.0%}, right cited {c.right_cited}"
            + (
                f", judge grounded {j.grounded:.2f}, fabricated {j.fabricated:.2f}, gap named {j.gap_named:.2f}"
                if j
                else ""
            )
            + ".*\n"
        )
        if x.note:
            add(f"> {x.note}\n")

    add("## 6. Revised scoring rules\n")
    add(
        f"The constants the evaluation runs with, after this calibration: an answer reads as ungrounded under "
        f"jev grounded {GROUNDED_FLOOR}, as adding a fact at jev fabricated {FABRICATED_CEILING} or over, and "
        f"needs {CITED_FLOOR:.0%} of its text cited to count as held; a reading in the {BAND[0]:.1f}–{BAND[1]:.1f} "
        "band is still one for a person.\n"
    )
    if cal.labels.revised_rules.strip():
        add(cal.labels.revised_rules.strip() + "\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out).rstrip() + "\n")
