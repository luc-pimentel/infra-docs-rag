"""`reports/evaluation.md`: two saved runs side by side, every metric, every gate, and the questions
whose result changed."""

from pathlib import Path

from ..ingest.report import cell
from .gates import Comparison, delta, yn
from .metrics import GROUPS, Metric


def arrow(before: Metric, after: Metric) -> str:
    """Whether the change is for the better, in the metric's own direction."""
    if before.value is None or after.value is None or before.value == after.value:
        return "="
    improved = (after.value > before.value) == (after.better == "higher")
    return "▲" if improved else "▼"


def write_report(cmp: Comparison, output: Path) -> None:
    b, c = cmp.baseline.manifest, cmp.candidate.manifest
    out: list[str] = []
    add = out.append
    add("# Evaluation report\n")
    add(
        f"Generated by `uv run infra-docs-rag evaluate-pipeline --baseline {cmp.baseline.name} --candidate "
        f"{cmp.candidate.name}` from two saved runs of the same {c.questions} questions, the retrieval benchmark "
        "plus the adversarial set, through the whole pipeline. Every metric is read off the saved answers; the "
        "gates in [`eval/gates.yaml`](../eval/gates.yaml) say which changes block.\n"
    )
    add("## Summary\n")
    add(
        f"**{cmp.verdict.capitalize()}.** "
        + (
            "Failed: "
            + "; ".join(
                f"`{r.gate.metric}` {r.gate.label} ({r.detail}){'' if r.gate.critical else ', warning'}"
                for r in cmp.failed
            )
            + "."
            if cmp.failed
            else "Every gate cleared."
        )
        + "\n"
    )
    add("| | Baseline | Candidate |\n|---|---|---|")
    add(f"| Run | `{cmp.baseline.name}` | `{cmp.candidate.name}` |")
    add(
        f"| Pipeline version | `{b.version}`: {b.description or '–'} | `{c.version}`: {c.description or '–'} |"
    )
    add(f"| Retrieval | `{b.retrieval.label}` | `{c.retrieval.label}` |")
    add(
        f"| Index | {b.index.model} · {b.index.chunking.label} · {b.index.chunks} chunks | {c.index.model} · {c.index.chunking.label} · {c.index.chunks} chunks |"
    )
    add(
        f"| Generator | `{b.generator}` via {b.backend}, effort {b.effort}, prompt `{b.prompt_sha256}` | `{c.generator}` via {c.backend}, effort {c.effort}, prompt `{c.prompt_sha256}` |"
    )
    add(f"| Judge | {b.judge or 'none'} | {c.judge or 'none'} |")
    add(
        f"| Run | {b.created_at[:10]} at `{b.git_sha}` on {b.machine} | {c.created_at[:10]} at `{c.git_sha}` on {c.machine} |"
    )
    add("")

    def index_key(m):
        return (m.index.model_id, m.index.revision, m.index.chunking, m.index.chunks, m.index.ingest_version)

    shared = {
        "index": index_key(b) == index_key(c),
        "generator": b.generator == c.generator,
        "backend": b.backend == c.backend,
        "prompt": b.prompt_sha256 == c.prompt_sha256,
        "effort": b.effort == c.effort,
    }
    same = [k for k, v in shared.items() if v]
    differ = [k for k, v in shared.items() if not v]
    add(
        ("The two runs share " + ", ".join(same) + "; " if same else "")
        + (
            "they differ in "
            + ", ".join(differ)
            + " as well as retrieval, so a change below is not retrieval's alone."
            if differ
            else "only the retrieval differs, so every change below is the retrieval's."
        )
        + "\n"
    )

    add("## 1. Gates\n")
    add("| Gate | Rule | Baseline | Candidate | Change | Result | Why |")
    add("|---|---|---|---|---|---|---|")
    for r in cmp.results:
        result = "pass" if r.passed else ("**FAIL**" if r.gate.critical else "warn")
        add(
            f"| `{r.gate.metric}` | {r.gate.label} | {r.baseline.shown if r.baseline else '–'} | {r.candidate.shown} | "
            f"{delta(r.baseline, r.candidate) if r.baseline else '–'} | {result} | {cell(r.gate.why)} |"
        )
    add("")

    add("## 2. Every metric\n")
    add("▲ is a change for the better in the metric's own direction, ▼ for the worse.\n")
    for group, title in GROUPS.items():
        names = [n for n in cmp.after if n.startswith(group + ".")]
        if not names:
            continue
        add(f"**{title}**\n")
        add("| Metric | Baseline | Candidate | Change | | What it measures |")
        add("|---|---|---|---|:-:|---|")
        for n in names:
            before, after = cmp.before[n], cmp.after[n]
            add(
                f"| `{n}` | {before.shown} | {after.shown} | {delta(before, after)} | {arrow(before, after)} | {after.description} |"
            )
        add("")

    add("## 3. What changed, question by question\n")
    if not cmp.changed:
        add("No question's outcome, verdict or right-passage checks changed between the two runs.\n")
    else:
        better = [x for x in cmp.changed if x.better is True]
        worse = [x for x in cmp.changed if x.better is False]
        neither = [x for x in cmp.changed if x.better is None]
        add(
            f"{len(cmp.changed)} questions differ: {len(better)} now hold that did not, {len(worse)} held and no "
            f"longer do, {len(neither)} changed without the verdict flipping.\n"
        )
        add("| Query | Kind | Expected | What changed | Before | After |")
        add("|---|---|---|---|---|---|")
        for x in cmp.changed:
            add(
                f"| `{x.id}` | {x.after.kind} | {x.after.expect} | {'; '.join(x.what)} | "
                f"{shown(x.before)} | {shown(x.after)} |"
            )
        add("")
        if worse:
            add("The regressions in full:\n")
            for x in worse:
                add(f"### `{x.id}` · {x.after.kind} · expected to {x.after.expect}\n")
                add(f"**Q:** {x.after.question}\n")
                add(
                    f"**Baseline** ({x.before.verdict}): "
                    + (x.before.marked or x.before.reason or x.before.outcome).replace("\n", "\n> ")
                    + "\n"
                )
                add("Passages: " + passages(x.before) + "\n")
                add(
                    f"**Candidate** ({x.after.verdict}): "
                    + (x.after.marked or x.after.reason or x.after.outcome).replace("\n", "\n> ")
                    + "\n"
                )
                add("Passages: " + passages(x.after) + "\n")

    add("## 4. Reading the report\n")
    add(
        "A gate compares one metric: `no-drop` and `no-rise` against the baseline with the tolerance the gate "
        "names, `min` and `max` against a fixed value. A critical gate that fails blocks (the command exits 1); "
        "the others warn. Retrieval metrics count the labelled in-scope questions, grounding metrics the answered "
        "ones among them, abstention the out-of-scope and adversarial sets. Costs are at API list prices for the "
        "tokens the run used, whatever it was billed to; latency is retrieval plus the model's time, on the "
        "machine named above.\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out).rstrip() + "\n")


def shown(c) -> str:
    return (
        f"{c.outcome}, right retrieved {yn(c.right_retrieved)}, right cited {yn(c.right_cited)}, "
        f"{c.cited_share:.0%} cited"
        if c.answered
        else f"{c.outcome}, right retrieved {yn(c.right_retrieved)}"
    )


def passages(c) -> str:
    return "; ".join(f"[{s.n}] `{cell(s.citation)}`" + (" ✓" if s.right else "") for s in c.sources) or "none"
