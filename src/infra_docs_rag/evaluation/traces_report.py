"""`reports/traces.md`: the trace schema as the eval reads it (the tags and the spans), one captured
trace in full, every failed record of each run diagnosed from its trace, and a few cases walked
through from the score to the span that broke."""

from collections import Counter
from pathlib import Path

from ..ingest.report import cell
from ..observe.trace import Trace, render
from .dataset import Record
from .diagnose import STAGE_OF, Diagnosis
from .runs import Run

TAGS = [
    ("example_id", "the record (or benchmark question) the answer is for"),
    ("run", "the saved run under `eval/runs/` the trace belongs to"),
    ("dataset_version", "`<records>+<hash>` of the dataset the run answered (section 9 of the spec)"),
    ("version", "the pipeline version, from `eval/versions.yaml`"),
    ("prompt_version", "`<name>+<hash of the wording>`"),
    ("model_version", "the generator's model id"),
    ("retriever_version", "`<version>+<hash of the retrieval configuration>`"),
    ("index_version", "the hash of the index read"),
]
SPANS = [
    (
        "retrieve",
        "embed → dense + lexical → fuse → rerank → pack",
        "candidates, first-stage and reranked depth, packed, dropped under the floor and past the budget, top score, what degraded",
    ),
    (
        "prompt",
        "the passages under their headings, the system prompt",
        "passages, tokens, budget, prompt version",
    ),
    ("generate", "the model call", "model, tokens in and out, cost, outcome, error"),
    (
        "verify",
        "every typed citation checked against its passage",
        "citations, cited chunks, cited share, claim share, uncited segments",
    ),
    ("judge", "jev on the answer against the passages", "grounded, fabricated, gap named"),
    (
        "read",
        "jev on the answer against the reference",
        "relevant, agrees with the reference, deprecation named, readings named",
    ),
]


def fmt(v) -> str:
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:.3f}" if abs(v) < 10 else f"{v:,.0f}"
    return str(v)


def pick_cases(results: dict[str, list[Diagnosis]], limit: int = 3) -> list[tuple[str, str]]:
    """One case per cause, latest run first, up to `limit`: (run, record id)."""
    seen: set[str] = set()
    out: list[tuple[str, str]] = []
    for run_name in reversed(list(results)):
        for d in results[run_name]:
            if d.cause == "held" or d.cause in seen:
                continue
            seen.add(d.cause)
            out.append((run_name, d.id))
            if len(out) == limit:
                return out
    return out


def write_report(
    runs: list[Run],
    records: list[Record],
    traces: dict[str, dict[str, Trace]],
    results: dict[str, list[Diagnosis]],
    output: Path,
    cases: list[str] | None = None,
    example: str | None = None,
) -> None:
    by_record = {r.id: r for r in records}
    lines: list[str] = []
    w = lines.append
    names = " ".join(f"--run {r.name}" for r in runs)
    w("# Traces: where a failed eval broke")
    w("")
    w(
        f"Generated by `uv run infra-docs-rag dataset diagnose {names}` from the traces each run saved beside "
        "itself (`eval/runs/<run>/traces.jsonl`, one per record, tagged with the record, the run and the dataset "
        "version) and the saved cases. A regression score ([`regression.md`](regression.md)) says that a record "
        "stopped holding; the trace says in which span. What each span holds is in "
        "[`eval/SPEC.md`](../eval/SPEC.md), section 10."
    )
    w("")
    w("## Summary")
    w("")
    w("| Run | Records | Failed | Retrieval | Prompt construction | Context overload | Generation | Traces |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|")
    for run in runs:
        ds = results[run.name]
        stages = Counter(d.stage for d in ds if d.cause != "held")
        w(
            f"| `{run.name}` | {len(ds)} | {sum(d.cause != 'held' for d in ds)} | {stages['retrieval']} | "
            f"{stages['prompt construction']} | {stages['context overload']} | {stages['generation']} | {len(traces[run.name])} |"
        )
    w("")

    w("## 1. The trace schema")
    w("")
    w(
        "Every answer writes one trace: the question, the pipeline version and its lineage, every stage's time, "
        "what the first stage ranked with its scores, what the reranker made of every candidate, what the pack "
        "step kept and what it dropped and why, what the model wrote and cited, what the judge and the reader "
        "read. Since stage 17 it carries the identifiers that link it to the eval example and the experiment:"
    )
    w("")
    w("| Tag | What it holds |")
    w("|---|---|")
    for tag, what in TAGS:
        w(f"| `{tag}` | {what} |")
    w("")
    w("and reads as spans, in request order, each with its time and the attributes a diagnosis needs:")
    w("")
    w("| Span | Covers | Attributes |")
    w("|---|---|---|")
    for name, covers, attrs in SPANS:
        w(f"| `{name}` | {covers} | {attrs} |")
    w("")
    w(
        "`trace_answer(...)` in `observe/trace.py` writes it; `Trace.tags` and `Trace.spans` read it back; the "
        "run keeps `trace_id` on each case, so a row in a report opens onto its trace."
    )
    w("")

    # 2. one captured trace
    shown: Trace | None = None
    shown_run = ""
    if example:
        for run in runs:
            if example in traces[run.name]:
                shown, shown_run = traces[run.name][example], run.name
    if shown is None:
        for run_name, rid in pick_cases(results, 1):
            shown, shown_run = traces[run_name].get(rid), run_name
    if shown is None:
        for run in runs:
            if traces[run.name]:
                shown = next(iter(traces[run.name].values()))
                shown_run = run.name
                break
    w("## 2. One captured trace")
    w("")
    if shown is None:
        w("No run given has traces saved beside it.")
        w("")
    else:
        w(f"Record `{shown.example_id}` of `{shown_run}`, trace `{shown.trace_id}`. The tags:")
        w("")
        w("| Tag | Value |")
        w("|---|---|")
        for tag, value in shown.tags.items():
            w(f"| `{tag}` | {cell(str(value)) if value else '–'} |")
        w("")
        w("The spans:")
        w("")
        w("| Span | ms | Attributes |")
        w("|---|---:|---|")
        for s in shown.spans:
            attrs = ", ".join(f"{k} {fmt(v)}" for k, v in s.attributes.items() if v is not None and v != "")
            w(f"| `{s.name}` | {s.ms:,.0f} | {cell(attrs)} |")
        w("")
        w("As a person reads it:")
        w("")
        w("```")
        w(render(shown))
        w("```")
        w("")

    w("## 3. Every failed record, diagnosed")
    w("")
    w(
        "**retrieval/first-stage**: the named passage is not among the candidates the first stage ranked. "
        "**retrieval/rerank**: the first stage handed it to the reranker, which put it past the top k. "
        "**retrieval/threshold**: it ranked, and the pack step dropped it under the cosine floor. "
        "**retrieval/budget**: it ranked, and the pack step ran out of tokens before it. "
        "**prompt/abstention**: an abstention expected, near-miss passages cleared the floor, and the prompt's "
        "rule did not hold against them. **prompt/instruction**: an instruction in the question and the answer "
        "followed it. **context/overload**: the context at its budget and the answer left partly uncited. "
        "**generation**: the named passage reached the model and the answer still failed, with nothing upstream "
        "to blame."
    )
    w("")
    for run in runs:
        w(f"**`{run.name}`**")
        w("")
        w("| Record | Category | Failure mode | Verdict | Cause | Evidence | Trace |")
        w("|---|---|---|---|---|---|---|")
        for d in results[run.name]:
            if d.cause == "held":
                continue
            r = by_record[d.id]
            w(
                f"| `{d.id}` | {r.category} | `{r.failure_mode}` | {d.verdict} | **{d.cause}** | {cell(d.evidence)} | "
                f"`{d.trace_id or '–'}` |"
            )
        w("")

    w("## 4. Three cases, from the score to the span")
    w("")
    picked = (
        [
            (run.name, rid)
            for rid in cases
            for run in reversed(runs)
            if rid in {d.id for d in results[run.name]}
        ]
        if cases
        else pick_cases(results)
    )
    chosen: list[tuple[str, str]] = []
    for item in picked:
        if item not in chosen and (
            not cases or results[item[0]] and any(d.id == item[1] for d in results[item[0]])
        ):
            chosen.append(item)
    if cases:  # one run per id: the latest that has it
        latest: dict[str, tuple[str, str]] = {}
        for run_name, rid in chosen:
            latest.setdefault(rid, (run_name, rid))
        chosen = list(latest.values())
    if not chosen:
        w("No failed record to walk through.")
        w("")
    for run_name, rid in chosen:
        d = next(x for x in results[run_name] if x.id == rid)
        r = by_record[rid]
        run = next(x for x in runs if x.name == run_name)
        c = run.by_id()[rid]
        t = traces[run_name].get(rid)
        w(f"### `{rid}` in `{run_name}` · {r.category} · `{r.failure_mode}` · expected {r.expect}")
        w("")
        w(f"**Q:** {c.question}")
        w("")
        w(
            f"**Score:** verdict *{c.verdict}*. **Cause:** `{d.cause}` ({d.stage}). **Evidence:** {d.evidence}."
        )
        w("")
        if t is None:
            w("No trace saved for this record.")
            w("")
            continue
        named = set(r.contexts)
        w(
            f"**retrieve** ({t.retrieve_ms:,.0f} ms): {t.candidates} candidates eligible; the first stage's top five:"
        )
        w("")
        for h in t.first_stage[:5]:
            w(f"- {h.rank}. {h.score:.3f} `{cell(h.citation)}`{' ✓ named' if h.chunk_id in named else ''}")
        past = [h for h in t.first_stage[5:] if h.chunk_id in named]
        for h in past:
            w(f"- … {h.rank}. {h.score:.3f} `{cell(h.citation)}` ✓ named")
        w("")
        if t.reranked:
            w(f"The reranker's order over {len(t.reranked)} candidates, the named passage marked:")
            w("")
            for h in t.reranked[:5]:
                w(
                    f"- {h.rank}. {h.score:.3f} (was {h.first_rank}.) `{cell(h.citation)}`{' ✓ named' if h.chunk_id in named else ''}"
                )
            for h in [h for h in t.reranked[5:] if h.chunk_id in named]:
                w(f"- … {h.rank}. {h.score:.3f} (was {h.first_rank}.) `{cell(h.citation)}` ✓ named")
            w("")
        if t.dropped:
            w(
                "Dropped by the pack step: "
                + "; ".join(f"{x.rank}. {x.reason} `{cell(x.citation)}`" for x in t.dropped)
                + "."
            )
            w("")
        w(
            f"**prompt**: {len(t.context)} passages"
            + (f", {t.tokens:,} tokens" if t.tokens is not None else "")
            + (f" of a {t.budget:,} budget" if t.budget else "")
            + (f", {t.over_budget} left out" if t.over_budget else "")
            + ": "
            + "; ".join(
                f"[{h.rank}] `{cell(h.citation)}`{' ✓' if h.chunk_id in named else ''}" for h in t.context
            )
            + "."
        )
        w("")
        if "generate" in t.stages:
            w(
                f"**generate** ({t.stages['generate']:,.0f} ms): `{t.generator}`, {t.input_tokens:,} tokens in, "
                f"{t.output_tokens:,} out; outcome {t.outcome}" + (f" ({t.reason})" if t.reason else "") + "."
            )
            w("")
        if t.answered:
            w(
                f"**verify**: {len(t.citations)} citations, {t.claim_share:.0%} of the claims cited"
                + (f", {len(t.uncited)} uncited segment(s)" if t.uncited else "")
                + "."
            )
            w("")
            w("> " + " ".join(t.answer.split())[:700] + ("…" if len(t.answer) > 700 else ""))
            w("")
        if t.judgement:
            j = t.judgement
            w(
                f"**judge**: grounded {j.grounded:.2f}, fabricated {j.fabricated:.2f}, gap named {j.gap_named:.2f}."
            )
            w("")
        if t.reading:
            rd = t.reading
            w(f"**read**: relevant {rd.relevant:.2f}, agrees with the reference {rd.reference_agrees:.2f}.")
            w("")
        w(f"**Reference:** {' '.join(r.reference_answer.split())}")
        w("")

    w("## 5. The process")
    w("")
    w(
        "1. `dataset compare` names the records that stopped holding and links each to its trace in both runs. "
        "2. `dataset diagnose` reads the trace and names the span: for a record that names its passages, whether "
        "they ranked, where the reranker put them, whether the pack step dropped them and why; for one that "
        "reached the model, whether the prompt held, whether the context was at its budget, else generation. "
        "3. The cause decides the fix: a first-stage miss is a chunking or embedding question, a rerank miss a "
        "depth or model question, a budget drop a packing question, a prompt failure a wording question, and a "
        "generation failure a model or effort question. 4. The fix is a pipeline version; the regression test "
        "measures it; the trace of the fixed record shows the span that moved."
    )
    w("")
    w("```sh")
    w(
        "uv run infra-docs-rag dataset run --generator claude-code --version <name>   # writes eval/runs/<run>/traces.jsonl beside the run"
    )
    w(f"uv run infra-docs-rag dataset diagnose {names}   # this report")
    w(
        "uv run infra-docs-rag traces --id <trace_id>                                  # one trace in full, from the log"
    )
    w(
        "uv run python scripts/backfill_traces.py eval/runs/<run>                     # traces for a run made before stage 17: the saved answer, the retrieval replayed"
    )
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")


__all__ = ["write_report", "pick_cases", "STAGE_OF"]
