"""`reports/efficiency.md`: every saved run's quality, spend and speed side by side, the tradeoff
verdict on each before/after pair, the budgets and where every run stands against them."""

from pathlib import Path

from ..ingest.report import cell
from .efficiency import (
    COST_RISE,
    FREE_DROP,
    LATENCY_RISE,
    QUALITY_RECORDS,
    Budget,
    Numbers,
    Tradeoff,
    budget_status,
    share,
)
from .runs import Run


def usd(x: float) -> str:
    return f"${x:.4f}" if x < 0.01 else f"${x:.2f}"


def ms(x: float) -> str:
    return f"{x:,.0f} ms"


def write_report(
    numbers: list[Numbers],
    tradeoffs: list[tuple[str, Tradeoff]],
    budget_list: list[Budget],
    runs: dict[str, Run],
    release_run: str | None,
    baseline_run: str | None,
    output: Path,
) -> None:
    lines: list[str] = []
    w = lines.append
    w("# Efficiency: quality, spend and speed, side by side")
    w("")
    w(
        f"Generated by `uv run infra-docs-rag evaluate-efficiency` from the {len(numbers)} saved runs under `eval/runs/`. "
        "Cost is at API list prices for the tokens each run used, whatever it was billed to (the `claude-code` backend "
        "runs on a subscription); latency is retrieval plus the model's time per question on the machine the run names. "
        "The budgets are the cost, latency and cache gates in [`eval/gates.yaml`](../eval/gates.yaml) (the release) and "
        "[`eval/matrix.yaml`](../eval/matrix.yaml) (a dataset run); the tradeoff rule is in `evaluation/efficiency.py`. "
        "What each number reads is in [`eval/SPEC.md`](../eval/SPEC.md), section 13."
    )
    w("")
    w("## Summary")
    w("")
    w(
        "| Run | Kind | n | Held | Calls | Cached | Tokens | Cost / request | Judge | Mean | p50 | p95 | Held / $ | Held / min p95 |"
    )
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for x in numbers:
        mark = " ◂ release" if x.run == release_run else " ◂ baseline" if x.run == baseline_run else ""
        w(
            f"| `{x.run}`{mark} | {x.kind} | {x.n} | {x.held}/{x.n} ({x.held_share:.0%}) | {x.calls} | "
            f"{f'{x.cached}/{x.calls}' if x.cached else '–'} | {x.tokens:,} | {usd(x.cost_per_request)} | {usd(x.judge_usd)} | "
            f"{ms(x.mean_ms)} | {ms(x.p50_ms)} | {ms(x.p95_ms)} | "
            f"{f'{x.held_per_dollar:,.0f}' if x.held_per_dollar else '∞'} | {x.held_per_minute_p95:,.0f} |"
        )
    w("")
    w(
        "Tokens are input plus output over the run; the input side is the system prompt and the passages, so the "
        "cost per request moves with the token budget (stage 11) and the prompt, not with the answer. *Held / $* is "
        "records held per dollar of generation; *Held / min p95* is records held per minute of 95th-percentile wait: "
        "the quality a second buys."
    )
    w("")

    w("## 1. Tradeoffs: is the better option worth what it costs?")
    w("")
    w(
        f"The rule: a change **buys quality** when it holds at least {QUALITY_RECORDS} records more (one is noise); it is "
        f"**worth it** when it does so within {COST_RISE:.0%} more cost per request and {LATENCY_RISE:.0%} more p95, "
        f"**not worth it** past either, **free** when the quality is flat and the cost or the p95 drops by {FREE_DROP:.0%} "
        "or more, and **a loss** when it holds fewer. Flat quality bought with more cost or time is not worth it."
    )
    w("")
    w("| Pair | Baseline → candidate | Held | Cost / request | p95 | Verdict | Why |")
    w("|---|---|---|---|---|---|---|")
    for name, t in tradeoffs:
        b, c = t.baseline, t.candidate
        w(
            f"| {name} | `{b.run}` → `{c.run}` | {b.held}/{b.n} → {c.held}/{c.n} ({t.held_delta:+d}) | "
            f"{usd(b.cost_per_request)} → {usd(c.cost_per_request)} ({share(t.cost_delta)}) | "
            f"{ms(b.p95_ms)} → {ms(c.p95_ms)} ({share(t.p95_delta)}) | **{t.verdict}** | {cell(t.why)} |"
        )
    w("")

    w("## 2. The budgets")
    w("")
    w(
        "Operational limits a release may not cross whatever the quality gain, as gates: a critical one blocks the "
        "release (`pipeline release`) or the dataset comparison (`dataset compare`); a non-critical one warns. A gate "
        "that is skipped when not measured (the cache hit share) applies only to a run that answered from the cache."
    )
    w("")
    cols = [n for n in (release_run, baseline_run) if n]
    others = [n for n in sorted(runs) if n not in cols]
    shown = cols + others
    w("| Where | Metric | Rule | Critical | " + " | ".join(f"`{n}`" for n in shown) + " | Why |")
    w("|---|---|---|---|" + "---|" * len(shown) + "---|")
    for b in budget_list:
        cells = []
        for n in shown:
            passed, value = budget_status(b, runs[n])
            cells.append("–" if passed is None else f"{value} {'✓' if passed else '**✗**'}")
        w(
            f"| {b.where}{f' · `{b.slice}`' if b.slice else ''} | `{b.gate.metric}` | {b.label} | {'yes' if b.gate.critical else 'warn'} | "
            + " | ".join(cells)
            + f" | {cell(b.gate.why)} |"
        )
    w("")

    w("## 3. Reading the report")
    w("")
    w(
        "Quality, spend and speed are one decision, not three: the regression report says what a change held, this one "
        "says what it paid. A candidate that clears every slice gate and breaks a budget is still refused; a candidate "
        "that holds the same records cheaper or faster is the change worth shipping first. The replay row is the cache's "
        "ceiling: the same answers at no cost and retrieval's latency alone, which is what a repeated question costs in "
        "production."
    )
    w("")
    w("```sh")
    w("uv run infra-docs-rag evaluate-efficiency                       # this report")
    w(
        "uv run infra-docs-rag evaluate-grounding --cache --save <run>-replay   # a replay through the cache, to measure the hit share"
    )
    w(
        "uv run infra-docs-rag evaluate-pipeline --list-metrics           # the cost, latency and cache metrics a gate can name"
    )
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")
