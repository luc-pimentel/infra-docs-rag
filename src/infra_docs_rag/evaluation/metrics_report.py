"""`reports/metrics.md`: the baseline score report over a dataset run. The matrix with each failure
mode's metric read on its slice, the overall and per-slice scores for retrieval, faithfulness and
relevance, where each failed record's failure sits (retrieval or generation), and the slice gates."""

from collections import Counter
from pathlib import Path

from ..ingest.report import cell
from .dataset import CATEGORIES, Record
from .metrics import Metric
from .runs import Run
from .slices import (
    ALL,
    SLICE_FIELDS,
    Diagnosis,
    MatrixResult,
    SliceGateResult,
    slice_name,
)

# What the per-slice tables show, in order: name, header.
COLUMNS = [
    ("retrieval.context_recall", "ctx recall"),
    ("retrieval.right_retrieved", "right read"),
    ("faithfulness.claim_cited_median", "claims cited"),
    ("faithfulness.judge_grounded", "grounded"),
    ("faithfulness.judge_fabricated", "fabricated"),
    ("relevance.judge_relevant", "relevant"),
    ("relevance.reference_agrees", "agrees"),
    ("abstention.expected", "abstained ✓"),
    ("abstention.false", "abstained ✗"),
    ("answers.held", "held"),
]


def shown(table: dict[str, Metric], name: str) -> str:
    m = table.get(name)
    return "–" if m is None or m.value is None else m.shown


def mark(passed: bool | None) -> str:
    return "–" if passed is None else ("pass" if passed else "**fail**")


def write_report(
    run: Run,
    records: list[Record],
    slices: dict[str, dict[str, Metric]],
    matrix: list[MatrixResult],
    gates: list[SliceGateResult],
    diagnosis: dict[str, tuple[Diagnosis, str]],
    baseline: Run | None,
    output: Path,
) -> None:
    by_record = {r.id: r for r in records}
    cases = [c for c in run.cases if c.id in by_record]
    m = run.manifest
    overall = slices[ALL]
    lines: list[str] = []
    w = lines.append

    w("# Metrics report")
    w("")
    w(
        f"Generated by `uv run infra-docs-rag dataset metrics --run {run.name}`"
        + (f" `--baseline {baseline.name}`" if baseline else "")
        + f" from the saved dataset run of {len(cases)} records through the `{m.version}` pipeline "
        f"({m.retrieval.label}; `{m.generator}` via {m.backend}, effort {m.effort}; judge {m.judge or 'none'}; "
        f"{m.created_at[:10]} at `{m.git_sha}`). The matrix and the gates are [`eval/matrix.yaml`](../eval/matrix.yaml); "
        "the records are [`eval/dataset/records.yaml`](../eval/dataset/records.yaml); what each metric reads is in "
        "[`eval/SPEC.md`](../eval/SPEC.md), section 7."
    )
    w("")
    w("## Summary")
    w("")
    blocked = [g for g in gates if g.blocks]
    warned = [g for g in gates if not g.skipped and not g.result.passed and not g.gate.critical]
    verdict = (
        f"**Blocked:** {len(blocked)} critical gate(s) failed."
        if blocked
        else f"**Passes** with {len(warned)} warning(s)."
        if warned
        else "**Passes.** Every gate cleared."
    )
    w(verdict)
    w("")
    kinds = Counter(d for d, _ in diagnosis.values())
    w("| | |")
    w("|---|---|")
    w(
        f"| Records | {len(cases)} ({sum(c.answered for c in cases)} answered, {sum(c.abstained for c in cases)} abstained, {sum(c.outcome not in ('answered', 'abstained', 'no-passage') for c in cases)} other) |"
    )
    w(
        f"| Retrieval | context recall {shown(overall, 'retrieval.context_recall')}, precision {shown(overall, 'retrieval.context_precision')}, a named passage read {shown(overall, 'retrieval.right_retrieved')}, MRR {shown(overall, 'retrieval.mrr')} |"
    )
    w(
        f"| Faithfulness | claims cited {shown(overall, 'faithfulness.claim_cited_median')} at the median, judge grounded {shown(overall, 'faithfulness.judge_grounded')}, fabricated {shown(overall, 'faithfulness.judge_fabricated')}, right passage cited {shown(overall, 'faithfulness.right_cited')} |"
    )
    w(
        f"| Relevance | relevant {shown(overall, 'relevance.judge_relevant')}, agrees with the reference {shown(overall, 'relevance.reference_agrees')} |"
    )
    w(
        f"| Abstention | expected and got {shown(overall, 'abstention.expected')}, false {shown(overall, 'abstention.false')} |"
    )
    w(f"| Expectations held | {shown(overall, 'answers.held')} |")
    w(
        f"| Where the failures sit | retrieval {kinds['retrieval']}, generation {kinds['generation']}, both {kinds['both']}, reading only {kinds['reading']} |"
    )
    w(
        f"| Matrix | {sum(1 for x in matrix if x.passed)} of {sum(1 for x in matrix if x.passed is not None)} targets met, {sum(1 for x in matrix if x.passed is False and x.entry.blocker)} blocker(s) missed |"
    )
    w(
        f"| Cost | generation {shown(overall, 'cost.usd_total')}, judge {shown(overall, 'cost.judge_usd')}, reader ${sum(c.reading.cost_usd for c in cases if c.reading):.4f} |"
    )
    w("")

    w("## 1. The matrix: failure mode → metric → threshold")
    w("")
    w(
        "Each failure mode the dataset is built around, the metric that measures it, the direction that is better, "
        "the threshold it is held to on the records designed for it, and where this run stands. A **blocker** is a "
        "miss the pipeline must not ship with; the other entries are targets."
    )
    w("")
    w("| Failure mode | Metric | Better | Threshold | Slice | This run | Result | Why |")
    w("|---|---|---|---|---|---|---|---|")
    for x in matrix:
        e = x.entry
        bound = f"{'≥' if e.rule == 'min' else '≤'} {e.value:g}"
        w(
            f"| `{e.failure_mode}` | `{e.metric}` | {e.direction} | {bound}{' · blocker' if e.blocker else ''} | `{e.slice}` "
            f"| {x.metric.shown if x.metric and x.metric.value is not None else '–'} | {mark(x.passed)} | {cell(e.why)} |"
        )
    w("")

    w("## 2. Scores, overall and per slice")
    w("")
    w(
        "ctx recall: share of the record's named passages the model read. right read: a named passage among the "
        "ones read. claims cited: the cited share of the answer's claims at the median. grounded, fabricated: the "
        "judge at its calibrated thresholds. relevant, agrees: the reader's two main questions. abstained ✓: "
        "records expecting an abstention that got one; abstained ✗: records expecting an answer that got one. "
        "held: the record's expectation held."
    )
    w("")
    header = "| Slice | n | " + " | ".join(h for _, h in COLUMNS) + " |"
    rule = "|---|---:|" + "---:|" * len(COLUMNS)

    def row(name: str, n: int) -> str:
        table = slices[name]
        return f"| `{name}` | {n} | " + " | ".join(shown(table, c) for c, _ in COLUMNS) + " |"

    w("**Overall**")
    w("")
    w(header)
    w(rule)
    w(row(ALL, len(cases)))
    w("")
    for field in SLICE_FIELDS:
        w(f"**By {field.replace('_', ' ')}**")
        w("")
        w(header)
        w(rule)
        values = CATEGORIES if field == "category" else sorted({getattr(r, field) for r in records})
        for v in values:
            name = slice_name(field, v)
            if name in slices:
                w(row(name, sum(getattr(r, field) == v for r in records)))
        w("")

    w("## 3. Retrieval problem or generation problem?")
    w("")
    w(
        "Every record whose expectation did not hold, and where its failure sits: **retrieval** when none of the "
        "record's named passages reached the model, **generation** when one did and the answer still failed (an "
        "abstention with the passage in hand, the wrong passage cited, claims left uncited), **both** when an "
        "abstention was expected, a near miss cleared the threshold and the model answered from it. **Reading** "
        "lists the records that held by the checks and that the judge or the reader disputes."
    )
    w("")
    w("| Diagnosis | Records |")
    w("|---|---:|")
    for d in ("retrieval", "generation", "both", "reading", "held"):
        w(f"| {d} | {kinds[d]} |")
    w("")
    w("| Record | Category | Failure mode | Expect | Outcome | Verdict | Diagnosis | Why |")
    w("|---|---|---|---|---|---|---|---|")
    for c in cases:
        d, why = diagnosis[c.id]
        if d == "held":
            continue
        r = by_record[c.id]
        w(
            f"| `{c.id}` | {r.category} | `{r.failure_mode}` | {r.expect} | {c.outcome} | {c.verdict} | **{d}** | {cell(why)} |"
        )
    w("")
    failed = [c for c in cases if diagnosis[c.id][0] in ("retrieval", "generation", "both")]
    if failed:
        w("The answers behind the failures, with the reference beside each:")
        w("")
        for c in failed:
            r = by_record[c.id]
            w(f"### `{c.id}` · {r.category} · `{r.failure_mode}` · expected {r.expect}: {c.verdict}")
            w("")
            w(f"**Q:** {c.question}")
            w("")
            w(f"**Reference:** {' '.join(r.reference_answer.split())}")
            w("")
            got = c.marked or c.text or f"({c.outcome}: {c.reason})"
            w(f"**Got:** {' '.join(got.split())}")
            w("")
            read = [f"[{s.n}] `{s.chunk_id}`{' ✓' if s.right else ''}" for s in c.sources]
            w(
                f"Read: {', '.join(read) if read else 'nothing qualified'}. Named: {', '.join(f'`{x}`' for x in r.contexts) or '–'}."
            )
            w("")

    w("## 4. The gates")
    w("")
    w(
        "The pass/fail rules a change has to clear, each on one slice. A critical gate that fails blocks (the "
        "command exits 1); a non-critical one warns. `no-drop` and `no-rise` need `--baseline`."
    )
    w("")
    w("| Slice | Metric | Rule | " + ("Baseline | " if baseline else "") + "This run | Result | Why |")
    w("|---|---|---|" + ("---|" if baseline else "") + "---|---|---|")
    for g in gates:
        res = g.result
        status = (
            "skipped" if g.skipped else "pass" if res.passed else ("**FAIL**" if g.gate.critical else "warn")
        )
        w(
            f"| `{g.gate.slice}` | `{g.gate.metric}` | {g.gate.label} | "
            + (f"{res.baseline.shown if res.baseline else '–'} | " if baseline else "")
            + f"{res.candidate.shown} | {status} | {cell(g.gate.why)} |"
        )
    w("")

    w("## 5. Reading the report")
    w("")
    w(
        "A slice of five records moves by 20% when one record flips, so the per-slice numbers locate a problem "
        "and the overall numbers and the gates decide. The matrix thresholds are targets read off this baseline; "
        "the four modes the benchmark could not measure (`stale-answer`, `wrong-reading`, `missing-hop`, "
        "`fabrication`) now have a number each, from the reader's deprecation and readings questions, the "
        "two-passage citation check and the judge's fabricated reading. The reader's probabilities are not yet "
        "calibrated against hand labels the way the judge's were in stage 08; that is the next stage, and until "
        "then the relevance and agreement gates are set loose."
    )
    w("")
    w("```sh")
    w(
        "uv run infra-docs-rag dataset run --generator claude-code                   # answer every record, judge and read each answer, save eval/runs/dataset-<version>-<generator>/"
    )
    w(
        f"uv run infra-docs-rag dataset metrics --run {run.name}      # this report; exit 1 when a critical gate fails"
    )
    w(
        f"uv run infra-docs-rag dataset metrics --run <candidate> --baseline {run.name}   # the same with the no-drop gates live"
    )
    w(
        "uv run infra-docs-rag dataset metrics --list-metrics                        # the names the matrix and the gates can use"
    )
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")
