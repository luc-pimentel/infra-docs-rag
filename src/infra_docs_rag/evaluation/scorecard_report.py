"""`reports/scorecard.md`: the latest status of every component of the evaluation system, and the
trend of every core metric over the releases and the dataset runs, with the critical slices and the
online windows. The one page a person opens first."""

from pathlib import Path

from ..ingest.report import cell
from .scorecard import CORE, SLICES, Scorecard, shown, sparkline

MARK = {"ok": "✅", "warn": "⚠️", "fail": "❌", "none": "–"}


def write_report(card: Scorecard, output: Path) -> None:
    lines: list[str] = []
    w = lines.append
    w("# Scorecard: the evaluation system at a glance")
    w("")
    w(
        "Generated by `uv run infra-docs-rag scorecard` from everything the repository holds: "
        "the saved runs, the releases, the baseline pin, the freeze, the safety runs, the online windows and the gates. "
        "No model call; the nightly job regenerates it and the PR check keeps it from drifting. The workflow it "
        "summarizes is [`docs/evals.md`](../docs/evals.md); the data behind it is `eval/scorecard.json`."
    )
    w("")
    w(f"## Status: {MARK[card.worst]} {card.worst}")
    w("")
    w("| Component | | Detail |")
    w("|---|:-:|---|")
    for s in card.statuses:
        w(f"| {s.component} | {MARK[s.state]} | {cell(s.detail)} |")
    w("")
    w(
        "release: what answers questions. baseline: the pinned dataset run every change is compared against. freeze: "
        "the assets release decisions are read under. quality gates: the committed candidate against the baseline. "
        "safety: the release version's graded safety run. budgets: the release run against the cost and latency "
        "limits. online: the latest window of live traffic against the baseline's rates."
    )
    w("")
    for series in card.series:
        title = "the releases, in order" if series.name == "releases" else "the dataset runs, in order"
        w(f"## Trends over {title}")
        w("")
        if not series.points:
            w("No run in this series yet.")
            w("")
            continue
        w(
            "| Metric | "
            + " | ".join(f"`{p.version}`<br>{p.date}" for p in series.points)
            + " | Trend | Latest |"
        )
        w("|---|" + "---:|" * len(series.points) + ":-:|---:|")
        for name, label, how in CORE:
            values = series.trend(name)
            if all(v is None for v in values):
                continue
            w(
                f"| {label} | "
                + " | ".join(shown(v, how) for v in values)
                + f" | `{sparkline(values)}` | {shown(values[-1], how)} |"
            )
        w("")
        w("Runs: " + ", ".join(f"`{p.run}`" for p in series.points) + ".")
        w("")
        if series.name == "dataset" and card.slices:
            w("**The critical slices** (expectations held, per dataset run):")
            w("")
            w("| Slice | " + " | ".join(f"`{p.version}`" for p in series.points) + " | Trend |")
            w("|---|" + "---:|" * len(series.points) + ":-:|")
            for st in card.slices:
                w(
                    f"| `{st.slice}` | "
                    + " | ".join(shown(v, "pct") for v in st.values)
                    + f" | `{sparkline(st.values)}` |"
                )
            w("")
            w("The slices the per-slice gates watch: " + ", ".join(f"`{s}`" for s in SLICES) + ".")
            w("")
    w("## The online windows")
    w("")
    if not card.windows:
        w("No window sampled yet.")
    else:
        w("| Window | Live | Sampled | Failed | Drift |")
        w("|---|---:|---:|---:|---|")
        for r in card.windows:
            w(
                f"| `{r.window}` | {r.live} | {r.sampled} | {r.failed} | {', '.join(f'`{x}`' for x in r.drifted) or 'none'} |"
            )
    w("")
    w("## Reading the scorecard")
    w("")
    w(
        "Red on the baseline or the freeze means the repository's own state moved under a decision (run the baseline "
        "again, or refreeze deliberately); red on the quality gates or safety is a candidate that must not ship; red on "
        "the budgets is the release itself over a limit. A trend bar reads left to right, oldest to latest, scaled to "
        "the metric's own range in the series, so a flat bar is a flat metric and a dip is a regression to read in "
        "[`regression.md`](regression.md). The releases and the dataset runs are two series because they answer two "
        "question sets."
    )
    w("")
    w("```sh")
    w("uv run infra-docs-rag scorecard            # this page and eval/scorecard.json")
    w("uv run infra-docs-rag pipeline health      # the live checks the service exposes at /health")
    w("```")
    w("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n")
