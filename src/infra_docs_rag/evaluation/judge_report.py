"""`reports/judge.md`: the rubric grader, the probability judge and the dataset reader against a
person's scores on the rubric, and the two readers against each other."""

from pathlib import Path

from .calibrate import Agreement
from .judge_calibrate import JudgeCalibration, judgement_of, reading_of
from .rubric import SCORES


def pct(value: float | None) -> str:
    return "–" if value is None else f"{value:.0%}"


def num(value: float | None) -> str:
    return "–" if value is None else f"{value:.2f}"


def sc(value: int | None) -> str:
    return "n/a" if value is None else str(value)


def counts(a: Agreement) -> str:
    return f"{a.tp} / {a.fp} / {a.fn} / {a.tn}"


def write_report(jc: JudgeCalibration, output: Path) -> None:
    m, r, cal, gs = jc.run.manifest, jc.rubric, jc.cal, jc.grades
    n, real, pert = len(cal.labels), len(cal.real), len(cal.perturbed)
    out: list[str] = []
    add = out.append
    add("# Judge calibration report\n")
    add(
        f"Generated by `uv run infra-docs-rag judge calibrate` from the rubric `{r.name}` "
        f"([`eval/rubric.yaml`](../eval/rubric.yaml)), the hand labels in "
        f"[`eval/calibration.yaml`](../eval/calibration.yaml) ({n} answers: {real} as the saved run "
        f"`{jc.run.name}` wrote them, {pert} perturbed; read twice, by {', '.join(f'{k}: {v}' for k, v in cal.readers.items())}; "
        f"resolved by {cal.resolved_by}) and the grades in `eval/runs/{jc.run.name}/grades.json` "
        f"(`{gs.model}` through `{gs.backend}` at effort `{gs.effort}`, prompt `{gs.prompt_sha256}`, graded "
        f"{gs.graded_at[:10]}, {len(gs.grades)} answers, ${gs.cost_usd:.2f} at list price). The run: pipeline "
        f"`{m.version}`, `{m.generator}` through `{m.backend}`, judged by `{m.judge}`, run {m.created_at[:10]} at "
        f"`{m.git_sha}`.\n"
    )
    add(
        "The question: when the grader scores an answer on groundedness, completeness and abstention, does "
        "a person reading the same passages and reference give the same score, and at which threshold does "
        "a score, or a probability, best read as pass or fail? The perturbed answers exist because the run "
        "produced no fabricated fact and no answer from memory on these records: each is a real answer with "
        "one such failure written in, so that the grader is measured on what it has to catch and not only on "
        "what it has to let through.\n"
    )

    add("## Summary\n")
    add("| | |\n|---|---|")
    add(f"| Answers labelled | {n} ({real} from the run, {pert} perturbed) |")
    for d in jc.dimensions:
        c = jc.counts(d.dimension)
        add(
            f"| Labels: {d.dimension} | "
            + ", ".join(f"{c[k]} × {k}" for k in ("2", "1", "0", "n/a") if c[k])
            + " |"
        )
    for d in jc.dimensions:
        best = d.best_pass_at
        add(
            f"| Grader: {d.dimension} | {pct(d.exact_share)} exact over {d.confusion.n} (weighted κ {num(d.kappa)}); "
            f"pass/fail at ≥ {d.pass_at}: {pct(d.pass_agreement.agreement)} (κ {num(d.pass_agreement.kappa)})"
            + (f"; best pass_at {best[0]} at {pct(best[1].agreement)}" if best else "")
            + " |"
        )
    o = jc.overall
    add(f"| Grader: overall verdict | {pct(o.agreement)} agreement over {o.n} (κ {num(o.kappa)}) |")
    for s in jc.signals:
        top = s.best
        add(
            f"| {s.name} | {pct(s.agreement.agreement)} agreement at {s.threshold:.2f} (κ {num(s.agreement.kappa)})"
            + (f"; best threshold {top[0]:.2f} at {pct(top[1].agreement)}" if top else "")
            + " |"
        )
    for ra in jc.readers:
        add(
            f"| Readers a vs b: {ra.dimension} | {ra.exact}/{ra.n} exact (weighted κ {num(ra.kappa)}), "
            f"{len(ra.disputed)} resolved |"
        )
    if jc.ungraded:
        add(f"| Not graded | {', '.join(f'`{x}`' for x in jc.ungraded)} |")
    add("")

    add("## 1. The rubric\n")
    add(
        "Three dimensions, each scored 0, 1 or 2 against one thing, null where it does not apply. The full "
        "definitions and the pass/fail examples are in [`eval/rubric.yaml`](../eval/rubric.yaml); the grader "
        "reads the definitions as written (not the examples), with the passages under the headings the "
        "model saw, the question, the reference answer and the marked answer.\n"
    )
    for dim in r.dimensions:
        add(f"- **{dim.id}**: {dim.question} Reads {dim.reads}. Applies when {dim.applies_when}.")
    add("")
    add(
        "A grade is also read as pass or fail at the operating threshold (`operating` in the rubric): "
        + ", ".join(f"{d.dimension} passes at ≥ {d.pass_at}" for d in jc.dimensions)
        + ". The overall verdict passes when every applicable dimension passes.\n"
    )

    add("## 2. What was labelled\n")
    add(
        "Every answer with the person's final score and the grader's, per dimension, and the probability "
        "judge's grounded and fabricated readings and the reader's agreement with the reference beside "
        "them. A perturbed answer is marked ~ in its id and carries its base case's passages, question and "
        "reference.\n"
    )
    add(
        "| Answer | Kind | Expected | Verdict | Person g / c / a | Grader g / c / a | jev grounded | jev fabricated | reader agrees |"
    )
    add("|---|---|---|---|---|---|---:|---:|---:|")
    by_id = gs.by_id()
    for item in jc.items:
        g = by_id.get(item.id)
        x = item.label
        j = judgement_of(item, gs)
        rd = reading_of(item, gs)
        person = " / ".join(sc(x.final(d)) for d in r.ids)
        grader = " / ".join(sc(g.score(d)) for d in r.ids) if g else "–"
        add(
            f"| `{item.id}` | {item.case.kind} | {item.case.expect} | {'perturbed' if x.perturbed else item.case.verdict} | "
            f"{person} | {grader} | {num(j.grounded) if j else '–'} | {num(j.fabricated) if j else '–'} | "
            f"{num(rd.reference_agrees) if rd else '–'} |"
        )
    add("")

    add("## 3. The grader against the person\n")
    add(
        "Per dimension: how often the two give the same score, the weighted κ over the scores (quadratic "
        "weights: a disagreement by two costs four times one by one; 1 is perfect, 0 is chance), and the "
        "pass/fail agreement at each threshold. The confusion matrix has the grader's score in the rows and "
        "the person's in the columns; off the diagonal is where they differ.\n"
    )
    for d in jc.dimensions:
        c = d.confusion
        add(f"### {d.dimension}\n")
        add(
            f"{c.exact} of {c.n} exact ({pct(d.exact_share)}), weighted κ {num(d.kappa)}, {c.off_by_two} off by two"
            + (
                f"; {c.grader_na_person_scored} scored by the person and not the grader, "
                f"{c.grader_scored_person_na} the other way round"
                if c.grader_na_person_scored or c.grader_scored_person_na
                else ""
            )
            + f"; {c.both_na} not applicable to either.\n"
        )
        add("| grader \\ person | 0 | 1 | 2 |")
        add("|---|---:|---:|---:|")
        for i in SCORES:
            add(f"| **{i}** | " + " | ".join(str(c.counts[i][j]) for j in SCORES) + " |")
        add("")
        add("| pass at ≥ | Agreement | κ | Precision | Recall | TP / FP / FN / TN |")
        add("|---:|---:|---:|---:|---:|---|")
        for t, a in d.pass_sweep:
            mark = " ◀" if t == d.pass_at else ""
            add(
                f"| {t}{mark} | {pct(a.agreement)} | {num(a.kappa)} | {pct(a.precision)} | {pct(a.recall)} | {counts(a)} |"
            )
        add("")

    add("## 4. The probability judge and the reader against the person\n")
    add(
        "The stage 08 judge (jev: grounded, fabricated) and the stage 14 reader (jev: relevant, agrees with "
        "the reference) read as yes at each threshold from 0.30 to 0.90, against the person's score on the "
        "matching dimension. The threshold in use is marked. On a real answer the probabilities are the "
        "run's; on a perturbed one `judge grade` asked jev the same questions.\n"
    )
    for s in jc.signals:
        add(f"**{s.name}** ({s.what}), against *{s.against}*, over {s.agreement.n}\n")
        add("| Threshold | Agreement | κ | Precision | Recall | TP / FP / FN / TN |")
        add("|---:|---:|---:|---:|---:|---|")
        for t, a in s.sweep:
            mark = " ◀" if abs(t - s.threshold) < 1e-9 else ""
            add(
                f"| {t:.2f}{mark} | {pct(a.agreement)} | {num(a.kappa)} | {pct(a.precision)} | {pct(a.recall)} | {counts(a)} |"
            )
        add("")

    add("## 5. The two readers\n")
    add(
        "Each answer was scored twice before the grader ran: reader a in the session that wrote the rubric, "
        "reader b in a fresh session given the rubric and the cases. Where they differed, the resolution "
        "names which reading stands and why; the final scores above are the resolved ones.\n"
    )
    add("| Dimension | Scored by both | Exact | Weighted κ | Resolved |")
    add("|---|---:|---:|---:|---|")
    for ra in jc.readers:
        add(
            f"| {ra.dimension} | {ra.n} | {ra.exact} ({pct(ra.exact / ra.n if ra.n else None)}) | {num(ra.kappa)} | "
            + (", ".join(f"`{x.id}`" for x in ra.disputed) or "–")
            + " |"
        )
    add("")
    resolved = [x for x in cal.labels if x.disputed()]
    for x in resolved:
        add(
            f"**`{x.id}`** ({', '.join(x.disputed())}): a {x.a.model_dump()}, b {x.b.model_dump() if x.b else {}}, final "
            f"{ {d: x.final(d) for d in r.ids} }.\n"
        )
        add(f"> {x.resolution.strip()}\n")

    add("## 6. Where the grader and the person differ\n")
    shown: dict[str, list[str]] = {}
    for d in jc.dimensions:
        for dis in d.disagreements:
            shown.setdefault(dis.item.id, []).append(
                f"**{d.dimension}**: grader {sc(dis.grader)}, person {sc(dis.person)}. Grader: {dis.reason or '–'}"
            )
    if not shown:
        add("None: the grader gave the person's score on every answer and dimension.\n")
    for item in jc.items:
        if item.id not in shown:
            continue
        x = item.label
        add(
            f"### `{item.id}` · {item.case.kind} · expected to {item.case.expect}"
            + (f" · perturbed: {x.perturbation}" if x.perturbed else "")
            + "\n"
        )
        add(f"**Q:** {item.case.question}\n")
        add("**A:** " + item.answer.replace("\n", "\n> ") + "\n")
        for line in shown[item.id]:
            add(f"- {line}")
        add("")
        if x.note:
            add(f"> Person: {x.note.strip()}\n")

    add("## 7. Operating thresholds\n")
    add(
        "What the evaluation reads the grader at after this calibration, written in `operating` in the "
        "rubric: "
        + "; ".join(f"**{d.dimension}** passes at ≥ {d.pass_at}" for d in jc.dimensions)
        + ". For each, the table in section 3 shows the agreement at the other threshold, and the summary "
        "names the one that agrees most. The probability thresholds the metrics use (`GROUNDED_FLOOR`, "
        "`FABRICATED_CEILING` in `evaluation/metrics.py`, 0.50 for the reader) are marked in section 4 "
        "against the same labels.\n"
    )
    add(
        "Limits of this round: the grader is the same model family as the generator, so a shared blind spot "
        "would not show here; the perturbed answers are failures by construction, which the grader has to "
        "catch but which say nothing about failures the run would actually produce; and the labels are a "
        "draft by one model session, read twice, for a person to review.\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out).rstrip() + "\n")
